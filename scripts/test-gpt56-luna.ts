// Копия эвристики looksLikeMultiStepWordProblem из lib/claude.ts (там не export —
// не стали расширять видимость внутренней функции ради одного тестового скрипта,
// сама эвристика короткая и стабильная, дублирование дешевле лишнего export).
function looksLikeMultiStepWordProblem(condition: string): boolean {
  const text = (condition || '').toLowerCase();
  if (/действие\s*\d/.test(text)) return true;
  const equalsCount = (text.match(/=/g) || []).length;
  if (equalsCount >= 2) return true;
  const digitGroups = text.match(/\d+/g) || [];
  const wordProblemMarkers = /(было|стало|осталось|всего|купил|потратил|решением|задач)/;
  return digitGroups.length >= 3 && wordProblemMarkers.test(text);
}

// 17.08.2026: реальный прод-кейс (фото 2.jpg, задание 10b "78 - 52 = ?") —
// модель посчитала верный ответ ребёнка (26) неверным. Ответ GPT: для
// голых арифметических примеров вообще не доверять модели ни чтение, ни
// вычисление одновременно в одном непроверяемом поле — вместо этого
// отдельным изолированным вызовом получить ТОЛЬКО распознавание (само
// выражение + что написал ученик, без оценки), а сравнение и итоговый
// status посчитать в коде через evalSimpleExpression (та же функция, что
// уже используется для банка карточек). Эвристика ловит только "голые"
// примеры вида "78 - 52 = ?" — без слов, ровно один оператор.
function isSimpleArithmeticExpression(condition: string): boolean {
  const text = (condition || '').trim();
  return /^\d+\s*[+\-×÷*/]\s*\d+\s*=\s*\??\s*$/.test(text);
}

// 17.08.2026, доработка после первого теста: обрезка по yStartPercent
// каждой отдельной задачи не подошла для этого случая — примеры в
// задании №10 расположены В ОДИН РЯД ПО ГОРИЗОНТАЛИ, а cropImageByPercent
// режет только по вертикали, поэтому кроп для КАЖДОГО примера захватывал
// всю строку (все 4 примера сразу), и модель либо не могла понять, какой
// именно ответ спрашивают (written_answer: null), либо путала соседние
// примеры между собой. Убрали кроп полностью для этого шага — один общий
// вызов на ВСЕ голые примеры сразу, по полному фото, с номером задания в
// каждом элементе (чтобы надёжно сопоставить результат обратно, не
// полагаясь на порядок). Изоляция кропом помогала там, где нужно было
// физически убрать ДРУГИЕ задания из поля зрения модели (многошаговая
// арифметика, банк карточек) — здесь другая природа проблемы (модель
// уверенно "довычисляла" chitaya, а не путала соседей), кроп тут не при
// делах.
function buildArithmeticOcrBatchPrompt(items: Array<{ number: string; condition: string }>): string {
  const list = items.map((t) => `- №${t.number}: "${t.condition}"`).join('\n');
  return `Ниже — список голых арифметических примеров со страницы школьной тетради (только числа и знак действия, без слов):
${list}

Для КАЖДОГО примера из списка найди его на фото и определи ДВЕ вещи дословно, посимвольно, как физически написано:
1. "expression" — само выражение примера, как оно написано в условии.
2. "written_answer" — что ученик написал в качестве ответа (только цифры, как они написаны).

НЕ вычисляй ничего сам и не оценивай, правильный ли ответ, — сейчас единственная цель дословно распознать оба поля для каждого примера. Если ответ ученика неразборчив — верни "written_answer": null для этого примера. Не путай соседние примеры между собой — сопоставляй по номеру задания.

Ответь строго JSON-объектом (не массивом — extractJson в этом скрипте ищет фигурные скобки), поле "results" — массив в ТОМ ЖЕ порядке, без markdown:
{"results": [{"number": "10a", "expression": "37 + 42", "written_answer": "71"}]}`;
}

async function callResponsesAPI(
  apiKey: string,
  body: Record<string, unknown>
): Promise<{ data: any; outputText: string | undefined }> {
  const response = await fetch('https://api.openai.com/v1/responses', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${apiKey}`
    },
    body: JSON.stringify(body)
  });

  const bodyText = await response.text();
  if (!response.ok) {
    console.error(`--- Ошибка API (${response.status}) ---`);
    console.error(bodyText);
    process.exit(1);
  }

  let data: any;
  try {
    data = JSON.parse(bodyText);
  } catch {
    console.error('Ответ не JSON:', bodyText.slice(0, 1000));
    process.exit(1);
  }

  // Реальный ответ модели лежит в output[].content[].text (не в data.output_text
  // напрямую — этого верхнеуровневого поля в ответе Responses API на практике не
  // было ни разу). Блоки type:"reasoning" с encrypted_content — это гигабайты
  // зашифрованного мусора, не выводим их целиком, чтобы не забивать вывод.
  const messageItem = (data.output || []).find((o: any) => o.type === 'message');
  const outputText: string | undefined = messageItem?.content?.find(
    (c: any) => c.type === 'output_text'
  )?.text;

  return { data, outputText };
}

function extractJson(text: string): any {
  let cleaned = text.replace(/^```json\s*/i, '').replace(/^```\s*/, '').replace(/```\s*$/, '').trim();
  const firstBrace = cleaned.indexOf('{');
  const lastBrace = cleaned.lastIndexOf('}');
  if (firstBrace !== -1 && lastBrace !== -1 && lastBrace > firstBrace) {
    cleaned = cleaned.slice(firstBrace, lastBrace + 1);
  }
  return JSON.parse(cleaned);
}

