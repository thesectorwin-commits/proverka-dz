export async function explainTaskOpenAI(
  image: ImageInput,
  task: {
    number?: string;
    condition?: string;
    yStartPercent?: number;
    yEndPercent?: number;
    xStartPercent?: number;
    xEndPercent?: number;
  }
): Promise<{ explanation: string; condition?: string; tokensInput: number; tokensOutput: number }> {
  let focusedImage = image;
  let cropNote = '';
  const hasKnownCondition = !!task.condition;
  if (task.yStartPercent != null && task.yEndPercent != null) {
    // См. тот же комментарий в explainTask (lib/claude.ts, 02.09.2026) —
    // ручная рамка уже точна сама по себе, дефолтный 6% Y-паддинг
    // (рассчитан на грубую AI-оценку из старого авто-детекта) на плотной
    // странице утягивает в кадр соседнее задание целиком.
    const yPaddingPercent = hasKnownCondition ? undefined : 2;
    const cropped = await cropImageByPercent(
      image,
      task.yStartPercent,
      task.yEndPercent,
      task.xStartPercent,
      task.xEndPercent,
      yPaddingPercent
    );
    if (cropped) {
      focusedImage = cropped;
    } else if (task.condition) {
      cropNote = ` Смотри именно на задание №${task.number}: "${task.condition}" — на фото есть и другие задания, их не трогай.`;
    }
  }
  const taskLine = hasKnownCondition
    ? `Задание №${task.number}: "${task.condition}"${cropNote}`
    : EXPLAIN_TASK_UNKNOWN_CONDITION_NOTE;
  const responseSchema = hasKnownCondition
    ? `{"explanation": "текст подсказки для ребёнка, 3-5 предложений"}`
    : `{"condition": "коротко, как ты понял задание, одним предложением", "explanation": "текст подсказки для ребёнка, 3-5 предложений"}`;

  const promptText = `${EXPLAIN_TASK_PROMPT_HEADER}

${taskLine}

Ответь строго JSON, без markdown:
${responseSchema}`;

  const { parsed, tokensInput, tokensOutput } = await callOpenAIResponsesJsonWithRetry(
    {
      model: MODEL,
      reasoning: { effort: 'none' },
      input: [{ role: 'user', content: [{ type: 'input_text', text: promptText }, toImageBlock(focusedImage)] }]
    },
    (text) => extractJson(text) as { explanation?: string; condition?: string }
  );

  return {
    explanation: parsed?.explanation || '',
    condition: hasKnownCondition ? task.condition : parsed?.condition,
    tokensInput,
    tokensOutput
  };
}

