// 18.08.2026: "prefetchedDetect" — если детект банка уже получен ПОПУТНО
// с классификацией предмета (см. CLASSIFY_AND_BANK_DETECT_PROMPT в
// checkHomeworkPhotoOpenAI, экономия одной лишней передачи картинки на
// каждую проверку), отдельный BANK_DETECT_PROMPT-вызов здесь не нужен —
// используем уже готовый результат. Если не передан (undefined) —
// прежнее поведение, свой вызов детекта (оставлено для scripts/test-*.ts
// и на случай, если комбинированный парсинг когда-нибудь не даст полей
// банка).
async function checkSharedAnswerBank(
  solutionImage: ImageInput,
  prefetchedDetect?: BankDetect
): Promise<{ tasks: CheckTask[]; tokensInput: number; tokensOutput: number }> {
  let tokensInput = 0;
  let tokensOutput = 0;
  const imageBlock = toImageBlock(solutionImage);

  let bankDetect: BankDetect;
  if (prefetchedDetect) {
    bankDetect = prefetchedDetect;
  } else {
    const { outputText: bankDetectText, usage: detectUsage } = await callOpenAIResponsesWithRetry({
      model: MODEL,
      reasoning: { effort: 'none' },
      input: [{ role: 'user', content: [{ type: 'input_text', text: BANK_DETECT_PROMPT }, imageBlock] }]
    });
    tokensInput += detectUsage?.input_tokens || 0;
    tokensOutput += detectUsage?.output_tokens || 0;

    if (!bankDetectText) return { tasks: [], tokensInput, tokensOutput };

    try {
      bankDetect = extractJson(bankDetectText);
    } catch (err) {
      console.error('Не удалось распарсить ответ детекции банка вариантов (OpenAI):', err);
      return { tasks: [], tokensInput, tokensOutput };
    }
  }

  if (!bankDetect.has_shared_bank || !bankDetect.tasks || bankDetect.tasks.length === 0) {
    return { tasks: [], tokensInput, tokensOutput };
  }
  // Локальная переменная вместо повторного bankDetect.tasks — TS не
  // гарантирует narrowing свойства объекта через await-границы так же
  // надёжно, как для простой переменной.
  const bankTasks: BankTask[] = bankDetect.tasks;

  const bankOptionsText = (bankDetect.options || []).map((o) => `Вариант ${o.number}: "${o.content}"`).join('\n');

  // Целевое восстановление по разрывам координат между уже найденными
  // задачами (см. историю в CLAUDE.md: полный повтор структурного вызова
  // с числовой подсказкой "ожидается N" оказался опасен — модель
  // дублировала задачи, чтобы подогнать число; заменено на локальные
  // проверки конкретных разрывов, без числовых подсказок).
  const GAP_THRESHOLD_PERCENT = 6;
  const sortedTasks = [...bankTasks].sort((a, b) => a.yStartPercent - b.yStartPercent);
  for (let i = 0; i < sortedTasks.length - 1; i++) {
    const gapStart = sortedTasks[i].yEndPercent;
    const gapEnd = sortedTasks[i + 1].yStartPercent;
    if (gapEnd - gapStart <= GAP_THRESHOLD_PERCENT) continue;

    const padding = 3;
    const crop = await cropImageByPercent(solutionImage, Math.max(0, gapStart - padding), Math.min(100, gapEnd + padding));
    if (!crop) continue;

    const { outputText: missingText, usage: missingUsage } = await callOpenAIResponsesWithRetry({
      model: MODEL,
      reasoning: { effort: 'none' },
      input: [{ role: 'user', content: [{ type: 'input_text', text: MISSING_TASK_DETECT_PROMPT }, toImageBlock(crop)] }]
    });
    tokensInput += missingUsage?.input_tokens || 0;
    tokensOutput += missingUsage?.output_tokens || 0;

    if (!missingText) continue;
    try {
      const missing = extractJson(missingText) as { has_task?: boolean; condition?: string; student_option?: number | null };
      if (missing.has_task && missing.condition) {
        bankTasks.push({
          id: `recovered-${gapStart}`,
          condition: missing.condition,
          student_option: missing.student_option ?? null,
          yStartPercent: gapStart,
          yEndPercent: gapEnd
        });
      }
    } catch (err) {
      console.error('Не удалось распарсить ответ проверки разрыва (банк вариантов, OpenAI):', err);
    }
  }

  // Независимое перечисление блоков (начало+конец текста, БЕЗ координат/
  // номеров/ожидаемого количества) + позиционное сопоставление по порядку
  // сверху вниз — ловит случаи, когда пропущенная задача не оставляет
  // видимого разрыва в координатах (модель просто сжимает границы
  // соседей). Подробности всех трёх итераций этого подхода — CLAUDE.md.
  const { outputText: blocksText, usage: blocksUsage } = await callOpenAIResponsesWithRetry({
    model: MODEL,
    reasoning: { effort: 'none' },
    input: [{ role: 'user', content: [{ type: 'input_text', text: buildBlockEnumeratorPrompt(bankOptionsText) }, imageBlock] }]
  });
  tokensInput += blocksUsage?.input_tokens || 0;
  tokensOutput += blocksUsage?.output_tokens || 0;

  if (blocksText) {
    try {
      const blocksResult = extractJson(blocksText) as { blocks?: Array<{ start: string; end: string }> };
      const blocks = Array.isArray(blocksResult.blocks) ? blocksResult.blocks : [];

      const MATCH_THRESHOLD = 0.6;
      const matchesTask = (block: { start: string; end: string }, condition: string): boolean => {
        const condWords = normalizeWords(condition);
        const startScore = matchScore(normalizeWords(block.start), condWords);
        const endScore = matchScore(normalizeWords(block.end), condWords);
        return startScore >= MATCH_THRESHOLD && endScore >= MATCH_THRESHOLD;
      };

      const orderedTasks = [...bankTasks].sort((a, b) => a.yStartPercent - b.yStartPercent);
      const unmatchedBlocks: Array<{ start: string; end: string }> = [];
      let blockIndex = 0;
      let taskPointer = 0;
      while (blockIndex < blocks.length) {
        const block = blocks[blockIndex];
        if (taskPointer < orderedTasks.length && matchesTask(block, orderedTasks[taskPointer].condition)) {
          blockIndex++;
          taskPointer++;
          continue;
        }
        if (taskPointer + 1 < orderedTasks.length && matchesTask(block, orderedTasks[taskPointer + 1].condition)) {
          taskPointer++;
          continue;
        }
        unmatchedBlocks.push(block);
        blockIndex++;
      }

      for (const block of unmatchedBlocks) {
        const { outputText: recoveryText, usage: recoveryUsage } = await callOpenAIResponsesWithRetry({
          model: MODEL,
          reasoning: { effort: 'none' },
          input: [
            {
              role: 'user',
              content: [{ type: 'input_text', text: buildTextAnchoredRecoveryPrompt(bankOptionsText, block.start, block.end) }, imageBlock]
            }
          ]
        });
        tokensInput += recoveryUsage?.input_tokens || 0;
        tokensOutput += recoveryUsage?.output_tokens || 0;
        if (!recoveryText) continue;

        try {
          const recovered = extractJson(recoveryText) as {
            has_task?: boolean;
            is_same_task_type?: boolean;
            condition?: string;
            student_option?: number | null;
            yStartPercent?: number;
            yEndPercent?: number;
          };

          // Двухуровневая защита (см. CLAUDE.md): TYPE_CHECK — это точно
          // задача данного типа, а не соседнее задание другого типа,
          // случайно захваченное перечислением блоков? — И реальная
          // (не null) отметка ученика, а не придуманная моделью.
          if (!recovered.has_task || !recovered.condition || !recovered.is_same_task_type || recovered.student_option == null) {
            continue;
          }
          const alreadyExists = bankTasks.some((t) =>
            matchesTask({ start: recovered.condition!, end: recovered.condition! }, t.condition)
          );
          if (!alreadyExists) {
            bankTasks.push({
              id: `recovered-text-${bankTasks.length + 1}`,
              condition: recovered.condition,
              student_option: recovered.student_option,
              yStartPercent: recovered.yStartPercent ?? 0,
              yEndPercent: recovered.yEndPercent ?? 100
            });
          }
        } catch (err) {
          console.error('Не удалось распарсить ответ targeted recovery (банк вариантов, OpenAI):', err);
        }
      }
    } catch (err) {
      console.error('Не удалось распарсить ответ BLOCK_ENUMERATOR (OpenAI):', err);
    }
  }

  // Значения карточек банка — считаем в коде, а не доверяем модели.
  const bankOptionValues = (bankDetect.options || []).map((o) => ({ number: o.number, value: evalSimpleExpression(o.content) }));

  const resultTasks: CheckTask[] = [];
  for (const task of bankTasks) {
    let taskImageBlock = imageBlock;
    if (task.yStartPercent != null && task.yEndPercent != null) {
      const crop = await cropImageByPercent(solutionImage, task.yStartPercent, task.yEndPercent);
      if (crop) taskImageBlock = toImageBlock(crop);
    }

    const { outputText: verifyText, usage: verifyUsage } = await callOpenAIResponsesWithRetry({
      model: MODEL,
      reasoning: { effort: 'none' },
      input: [{ role: 'user', content: [{ type: 'input_text', text: buildBankTaskVerifyPrompt(bankOptionsText, task.condition) }, taskImageBlock] }]
    });
    tokensInput += verifyUsage?.input_tokens || 0;
    tokensOutput += verifyUsage?.output_tokens || 0;
    if (!verifyText) continue;

    try {
      const verified = extractJson(verifyText) as { result?: number; correct_option?: number | null };

      // Приоритет — сопоставление result с посчитанными в коде значениями
      // карточек (устойчивее поля correct_option от модели — оно иногда
      // пустело даже при верно посчитанном result, см. CLAUDE.md).
      let correctOption: number | null = null;
      if (verified.result != null) {
        const matched = bankOptionValues.find((o) => o.value != null && Math.abs(o.value - (verified.result as number)) < 1e-9);
        if (matched) correctOption = matched.number;
      }
      if (correctOption == null) correctOption = verified.correct_option ?? null;

      // student_option — ТОЛЬКО из шага детекции (не перечитывается на
      // кропе — на практике оказалось менее надёжным для этой цифры).
      const studentOption = task.student_option ?? null;

      // status считает КОД, не модель.
      let status: CheckTask['status'];
      if (correctOption == null || studentOption == null) {
        status = 'unclear';
      } else {
        status = correctOption === studentOption ? 'correct' : 'incorrect';
      }

      const matchedOption = bankDetect.options?.find((o) => o.number === correctOption);
      const explanation =
        status === 'correct'
          ? ''
          : status === 'unclear'
          ? 'Не удалось уверенно определить номер правильного варианта или отметку ученика.'
          : `Правильный вариант — карточка ${correctOption}${matchedOption ? ` ("${matchedOption.content}")` : ''}. Ученик выбрал карточку ${studentOption}.`;
      const correctSolution = status === 'correct' && matchedOption ? `Карточка ${correctOption}: "${matchedOption.content}"` : '';

      resultTasks.push({
        number: '', // проставляется вызывающей стороной при мердже в общий список
        condition: task.condition,
        status,
        explanation,
        correct_solution: correctSolution
      });
    } catch (err) {
      console.error('Не удалось распарсить ответ изолированной проверки (банк вариантов, OpenAI):', err);
    }
  }

  return { tasks: resultTasks, tokensInput, tokensOutput };
}

