async function callOpenAIResponses(
  body: Record<string, unknown>
): Promise<{ outputText: string | undefined; usage?: { input_tokens: number; output_tokens: number } }> {
  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) {
    throw new Error('OPENAI_API_KEY не задан в переменных окружения сервера');
  }

  const response = await fetch(OPENAI_RESPONSES_URL, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${apiKey}` },
    body: JSON.stringify(body)
  });

  const bodyText = await response.text();
  if (!response.ok) {
    console.error('OpenAI API error:', response.status, bodyText);
    throw new Error(`Ошибка сервиса проверки (OpenAI, ${response.status})`);
  }

  let data: any;
  try {
    data = JSON.parse(bodyText);
  } catch (err) {
    console.error('OpenAI вернул не-JSON ответ:', bodyText.slice(0, 1000));
    throw new Error('Не удалось разобрать ответ модели — попробуйте более чёткое фото');
  }

  // Реальный текст ответа лежит в output[].content[].text у элемента с
  // type:"message" — верхнеуровневого data.output_text на практике не
  // бывает (проверено в scripts/test-gpt56-luna.ts).
  const messageItem = (data.output || []).find((o: any) => o.type === 'message');
  const outputText: string | undefined = messageItem?.content?.find((c: any) => c.type === 'output_text')?.text;

  return { outputText, usage: data.usage };
}

async function callOpenAIResponsesWithRetry(body: Record<string, unknown>) {
  try {
    return await callOpenAIResponses(body);
  } catch (err: any) {
    const msg = err?.message || '';
    if (msg.includes('Ошибка сервиса проверки') || msg.includes('fetch failed') || msg.includes('network')) {
      await new Promise((resolve) => setTimeout(resolve, 1500));
      return await callOpenAIResponses(body);
    }
    throw err;
  }
}

