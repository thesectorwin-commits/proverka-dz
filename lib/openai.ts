// двух вспомогательных функций он МОЛЧА ОТКЛЮЧАЛ ВСЮ ЗАЩИТУ (экран
// выбора задания/сверка номера пропускались целиком, будто задание на
// фото вообще не нашлось) — реальный владелец воспроизвёл именно это на
// заведомо неверном фото задания, которое ни разу до этого не давало
// сбоя в 6/6 изолированных тестах. Общий хелпер — ретрай ВСЕГО вызова
// (не повторный парсинг того же текста) один раз при ошибке парсинга.
async function callOpenAIResponsesJsonWithRetry<T>(
  body: Record<string, unknown>,
  parse: (text: string) => T
): Promise<{ parsed: T | null; tokensInput: number; tokensOutput: number }> {
  let tokensInput = 0;
  let tokensOutput = 0;
  for (let attempt = 1; attempt <= 2; attempt++) {
    const { outputText, usage } = await callOpenAIResponsesWithRetry(body);
    tokensInput += usage?.input_tokens || 0;
    tokensOutput += usage?.output_tokens || 0;
    if (!outputText) continue;
    try {
      return { parsed: parse(outputText), tokensInput, tokensOutput };
    } catch (err) {
      if (attempt === 2) console.error('Не удалось распарсить ответ модели после повторной попытки (OpenAI):', err);
    }
  }
  return { parsed: null, tokensInput, tokensOutput };
}

