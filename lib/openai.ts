// Значения карточек банка — простые арифметические выражения, считаем в
// коде (без eval/Function) и сопоставляем с числовым result от модели, а
// не доверяем полю correct_option напрямую (см. комментарий у
// buildBankTaskVerifyPrompt выше и историю в CLAUDE.md).
function evalSimpleExpression(expr: string): number | null {
  const s = expr.replace(/\s+/g, '').replace(/[−‐‑‒–—]/g, '-');
  let i = 0;

  function parseExpr(): number {
    let value = parseTerm();
    while (s[i] === '+' || s[i] === '-') {
      const op = s[i++];
      const rhs = parseTerm();
      value = op === '+' ? value + rhs : value - rhs;
    }
    return value;
  }

  function parseTerm(): number {
    let value = parseFactor();
    // ":" — школьная запись деления (см. isSimpleArithmeticExpression).
    while (s[i] === '*' || s[i] === '/' || s[i] === '×' || s[i] === '÷' || s[i] === ':') {
      const op = s[i++];
      const rhs = parseFactor();
      value = op === '*' || op === '×' ? value * rhs : value / rhs;
    }
    return value;
  }

  function parseFactor(): number {
    if (s[i] === '(') {
      i++;
      const value = parseExpr();
      if (s[i] === ')') i++;
      else throw new Error('unmatched paren');
      return value;
    }
    const start = i;
    while (i < s.length && /[0-9.]/.test(s[i])) i++;
    if (start === i) throw new Error('expected number');
    return parseFloat(s.slice(start, i));
  }

  try {
    if (!s) return null;
    const result = parseExpr();
    if (i !== s.length || Number.isNaN(result)) return null;
    return result;
  } catch {
    return null;
  }
}

// 02.09.2026: реальный прод-кейс — "семьи" из 2-3 взаимообратных равенств
// (например "76+18=94" / "94-18=76" / "94-76=18", написанных одно под
// другим БЕЗ буквенных подписей а)/б)/в)) в БОЛЬШИНСТВЕ прогонов теряли
// 8 из 12 равенств: основной вызов (шаг 2) создавал task только для
// ПЕРВОГО равенства каждой группы, остальные два молча пропадали без
// единого статуса. Текстовые правки промпта (одна принята и уже
// откачена — сделала только хуже, см. CLAUDE.md) не дали стабильного
// результата ни разу за несколько попыток. Решение — тот же принцип,
// что уже сработал для банка карточек: не полагаться на то, что
// основной вызов сам решит перечислить каждое равенство отдельным task,
// а НЕЗАВИСИМО найти их все на фото в этом же OCR-вызове (шаг 3.5) и
// добавить в код те, что основной вызов пропустил — гарантированно, а не
// понадеявшись на промпт. extractEquationLhs() — сравнение по левой части
// равенства (до "="), чтобы сопоставить "94 - 18 = ?" (task.condition от
// основного вызова) с "94-18" (expression от независимого детектора).
function extractEquationLhs(text: string): string {
  const eqIndex = text.indexOf('=');
  const lhs = eqIndex === -1 ? text : text.slice(0, eqIndex);
  return lhs.replace(/\s+/g, '').replace(/[−‐‑‒–—]/g, '-');
}

// 02.09.2026: english (Быкова) — реальный прод-кейс: подсказки в индексе
// отмечены чекбоксами вида "(✓)"/"(✗)" (например "I/a cat (✗)"), но модель
// на фото транскрибирует эту же отметку по-разному — иногда как символ,
// иногда как букву "x"/"X"/кириллическую "х" — раньше это считалось
// РАЗНЫМ словом при текстовом сопоставлении (matchScore), и итоговый
// score (2 совпадения слов из 3 ≈ 0.67) не дотягивал до порога 0.7 даже
// для правильно найденного задания. Вычёркиваем ВЕСЬ такой чекбокс целиком
// (скобка+один символ+скобка) ДО токенизации — не отдельные буквы "x" где
// угодно в тексте, это было бы риском для математики, где "x" — обычная
// переменная уравнения (например "x+8=12", без скобок вокруг — не тронуто).
function normalizeWords(text: string): string[] {
  return (text || '')
    .replace(/\(\s*[✓✗√×xXхХ]\s*\)/g, '')
    // 02.09.2026: english (Быкова) — подсказки вида "I/a radio" используют
    // "/" как компактный разделитель нескольких частей. Модель на фото
    // иногда транскрибирует его нестабильно (лишний пробел вокруг, лишний
    // слэш перед чекбоксом — реальный случай "dark hair/got/he/Has/ (x)"
    // вместо "...Has (✗)"), из-за чего целое слово-токен переставало
    // дословно совпадать (score 0.5 вместо 1.0). Заменяем "/" на пробел
    // ДО разбиения на слова — тогда результат не зависит от того, прилип
        // ли слэш к соседнему слову или превратился в отдельный токен.
    // Проверено (grep по textbook-index/*.json), что "/" нигде в индексе
    // не используется как дробь (не потеряем математический смысл).
    .replace(/\//g, ' ')
    .toLowerCase()
    // 05.09.2026: реальный кейс (Быкова) — модель транскрибирует
    // апостроф в английских сокращениях нестабильно: то прямой ' (уже
    // вырезался), то типографский ' (U+2019, не вырезался) — "What's"
    // вместо "What's". Оставшийся ' внутри слова превращал "what's" и
    // "whats" в РАЗНЫЕ токены, из-за чего дословно совпадающие условия
    // теряли score ниже порога 0.7 просто из-за формы кавычки, не
    // содержания. Добавлены типографские варианты кавычек/апострофа
    // (' ' " ") в тот же список, что и прямые — механическая, не
    // ИИ-зависимая правка.
    .replace(/[.,!?«»"'‘’“”();:]/g, '')
    .split(/\s+/)
    .filter(Boolean);
}

function matchScore(blockWords: string[], conditionWords: string[]): number {
  if (blockWords.length === 0) return 0;
  const condSet = new Set(conditionWords);
  const matched = blockWords.filter((w) => condSet.has(w)).length;
  return matched / blockWords.length;
}

function extractJson(text: string): any {
  let cleaned = text.replace(/^```json\s*/i, '').replace(/^```\s*/, '').replace(/```\s*$/, '').trim();
  const firstBrace = cleaned.indexOf('{');
  const lastBrace = cleaned.lastIndexOf('}');
  if (firstBrace !== -1 && lastBrace !== -1 && lastBrace > firstBrace) {
    cleaned = cleaned.slice(firstBrace, lastBrace + 1);
  }
  return JSON.parse(cleaned);
}

