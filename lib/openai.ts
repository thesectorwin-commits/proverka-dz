// Правило "всё-или-ничего на фото": если хоть одно распознанное на фото
// задание не сопоставилось уверенно с индексом ИЛИ имеет не-whitelisted
// answerType — весь индекс-путь отменяется, tryTextbookIndexCheck
// возвращает null, вызывающий код (app/api/checks/route.ts) откатывается
// на обычный полный пайплайн. Не собираем смешанный результат — проще и
// гарантированно не хуже базового поведения.
// ---------------------------------------------------------------------

export type NarrowItem = {
  id: string;
  displayCondition: string;
  // 22.08.2026: ровно одно из двух — knownAnswer (числовые типы, весь
  // существующий код продолжает читать его как раньше) ИЛИ
  // knownWordAnswer (fill_blank_word, первый нечисловой тип — русский
  // язык). buildIndexCheckTask разветвляется по тому, какое поле задано.
  knownAnswer?: number;
  knownWordAnswer?: string;
  // 22.08.2026: для fill_blank_word — грамматический вопрос ("какие?" и
  // т.п.), нужен только для текста безопасной подсказки при ошибке (см.
  // buildWordCheckTask), сам noun не нужен отдельно (уже в displayCondition).
  hintQuestion?: string;
  hintExpression?: string;
  // 21.08.2026: для word_problem/word_problems — шаги задачи (только
  // описания, БЕЗ чисел) для buildStepsHint. Не пересекается с
  // hintExpression (голая арифметика без слов) — заполняется только одно
  // из двух полей в зависимости от answerType.
  hintSteps?: { description: string }[];
  // 21.08.2026: для computation_list с requiresCheck (см. lib/textbookIndex.ts) —
  // проверочные равенства, которые ребёнок обязан приписать к примеру (не
  // только сам пример из hintExpression). См. buildCheckEquationSpecs выше.
  // 02.09.2026: раньше хранился только массив ожидаемых ЧИСЕЛ — теперь
  // полный текст каждого равенства, чтобы показать его отдельным пунктом.
  checkEquations?: Array<{ condition: string; expected: number }>;
  // 22.08.2026: для copy_and_mark_grammar (русский язык) — знание о том,
  // что этот item целиком другого рода: не "один ответ", а "весь известный
  // текст + список прилагательных с известной грамматической меткой".
  // См. buildCopyAndMarkCheckTask ниже.
  knownText?: string;
  knownAdjectives?: { word: string; number: string }[];
  // 28.08.2026: для number_sequence (пилот Петерсон) — несколько чисел
  // подряд (обычно 2), которые ребёнок должен дописать в правильном
  // порядке. См. buildSequenceCheckTask ниже.
  knownNumberSequence?: number[];
  // 01.09.2026: english (Быкова) — verb_form_fill, 1-2 пропуска в одном
  // предложении, слова по порядку (не числа) — тот же принцип, что
  // knownNumberSequence, только для слов. См. buildWordSequenceCheckTask.
  knownWordSequence?: string[];
  // 01.09.2026: english — word_categorization, МНОЖЕСТВО допустимых слов
  // для одной категории (порядок/количество не важны — ребёнок сам решает,
  // сколько слов дописать). См. buildCategoryCheckTask.
  knownWordSet?: string[];
  // 01.09.2026: english — sentence_from_cue, свободное предложение,
  // сравнение лояльное (LCS-diff по словам, как у copy_and_mark_grammar).
  // См. buildSentenceCheckTask.
  knownSentence?: string;
  // 03.09.2026: copy_text с выбором из нескольких печатных вариантов
  // ("спишите ЛЮБОЕ четверостишие") — если задано, buildSentenceCheckTask
  // сравнивает написанное со ВСЕМИ вариантами и засчитывает совпадение с
  // любым (не требует совпадения сразу со всеми). knownSentence в этом
  // случае не используется для сравнения, только как fallback-текст.
  knownSentenceOptions?: string[];
};

function letterFor(i: number): string {
  return String.fromCharCode(97 + i);
}

// 21.08.2026: реальный прод-кейс — задание "Вычисли И ПРОВЕРЬ решение"
// требует не только сам пример, но и 1-2 проверочных равенства (см. фото
// 9.jpg — "76+18=94" сопровождается "94-18=76" и "94-76=18"). Оба
// проверочных равенства для a+b=c — это c-a=b и c-b=a; для a-b=c — это
// a-c=b и c+b=a. Само СРАВНЕНИЕ по-прежнему только по РЕЗУЛЬТАТУ (число
// после "="), а не по левой части — не нужно требовать от модели читать
// точный вид проверочного равенства, достаточно сверить, что среди
// чисел, которые ребёнок написал как результат проверки, встретилось
// ожидаемое число. Так же надёжно ловит и вычислительную ошибку В САМОЙ
// проверке (если ребёнок посчитал проверочное равенство неверно, его
// результат не совпадёт ни с одним ожидаемым).
//
// 02.09.2026: реальный прод-кейс — по прямому запросу владельца каждое
// проверочное равенство теперь показывается ОТДЕЛЬНЫМ пунктом результата
// (как в обычном, не-индексном пайплайне), а не сворачивается внутрь
// статуса основного примера. Для этого нужен ТЕКСТ каждого проверочного
// равенства (не только пара чисел {a,b}) — вычисляем его в коде из
// исходного знака действия, а не из подобранных под ответ операндов.
function buildCheckEquationSpecs(
  expression: string,
  answer: number
): Array<{ condition: string; expected: number }> | null {
  const m = expression.match(/^\s*(\d+)\s*([+\-])\s*(\d+)\s*$/);
  if (!m) return null;
  const a = parseInt(m[1], 10);
  const op = m[2];
  const b = parseInt(m[3], 10);
  const c = answer;
  if (op === '+') {
    return [
      { condition: `${c} - ${a} = ?`, expected: b },
      { condition: `${c} - ${b} = ?`, expected: a }
    ];
  }
  return [
    { condition: `${a} - ${c} = ?`, expected: b },
    { condition: `${c} + ${b} = ?`, expected: a }
  ];
}

// Разворачивает один "task" индекса (может содержать несколько пунктов в
// items[]) в плоский список отдельных проверяемых пунктов — так же, как
// основной пайплайн показывает "1a"/"1b" вместо одной строки на весь
// номер, когда под одним номером несколько примеров.
export function buildNarrowItems(entry: IndexEntry): NarrowItem[] {
  const { task } = entry;
  switch (task.answerType) {
    case 'computation_list':
      return task.items.map((item, i) => {
        const checkEquations = task.requiresCheck ? buildCheckEquationSpecs(item.expression, item.answer) : null;
        return {
          id: `${task.number}${letterFor(i)}`,
          displayCondition: `${item.expression} = ?`,
          knownAnswer: item.answer,
          hintExpression: item.expression,
          // checkEquations === null (requiresCheck выключен, или выражение
          // не подошло под простой формат "a+b"/"a-b") — просто не требуем
          // проверку, деградация безопасна: сверяется только сам ответ.
          checkEquations: checkEquations || undefined
        };
      });
    case 'equations':
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: item.equation,
        knownAnswer: item.answer
      }));
    case 'fill_blank_equation':
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: item.expression_template,
        knownAnswer: item.answer
      }));
    case 'chain':
      // Фаза 1 сверяет только финальный ответ цепочки — intermediates
      // есть в индексе, но здесь не используются (см. lib/textbookIndex.ts,
      // "фаза 2, не в этом заходе").
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: `${item.start} ${item.steps.join(' ')} = ?`,
        knownAnswer: item.answer
      }));
    case 'word_problem':
      // Единственная задача под этим номером — prompt уже и есть полный
      // текст условия (см. lib/textbookIndex.ts, комментарий у типа).
      return [
        {
          id: task.number,
          displayCondition: task.prompt,
          knownAnswer: task.answer,
          hintSteps: task.steps
        }
      ];
    case 'word_problems':
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: item.condition,
        knownAnswer: item.answer,
        hintSteps: item.steps
      }));
    case 'fill_blank_word':
      // 22.08.2026: первый нечисловой тип (русский язык) — см.
      // lib/textbookIndex.ts. knownWordAnswer вместо knownAnswer.
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: `${item.noun} (${item.question})`,
        knownWordAnswer: item.answer,
        hintQuestion: item.question
      }));
    case 'copy_and_mark_grammar':
      // 22.08.2026: второй нечисловой тип — весь task ОДИН item (как
      // word_problem), но с известным текстом + списком прилагательных
      // вместо числового ответа. displayCondition — сам ожидаемый текст,
      // чтобы он был виден в результате проверки как "условие".
      return [
        {
          id: task.number,
          displayCondition: task.text,
          knownText: task.text,
          knownAdjectives: task.adjectives
        }
      ];
    case 'number_sequence':
      // 28.08.2026: пилот Петерсон — knownNumberSequence вместо knownAnswer
      // (ответ это НЕСКОЛЬКО чисел по порядку, не одно). См.
      // buildSequenceCheckTask.
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition:
          item.displayRow || `${item.given.join(', ')}, ... (закономерность: ${item.step} к каждому следующему)`,
        knownNumberSequence: item.answer
      }));
    case 'function_table':
      // 28.08.2026: пилот Петерсон — каждая ячейка таблицы "вход → выход"
      // становится отдельным пунктом с обычным числовым knownAnswer, тем
      // же путём, что и computation_list — отдельный компаратор не нужен.
      return task.tables.flatMap((table, tIdx) =>
        table.inputs.map((input, i) => ({
          id: `${task.number}${letterFor(tIdx)}${i + 1}`,
          displayCondition: `${input} ${table.operation} = ?`,
          knownAnswer: table.outputs[i]
        }))
      );
    case 'word_formation':
      // 28.08.2026: пилот Петерсон — словесная головоломка, но по факту
      // сравнения это тот же случай, что и fill_blank_word (одно известное
      // верное слово) — переиспользуем knownWordAnswer как есть.
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: item.base,
        knownWordAnswer: item.answer
      }));
    // 01.09.2026: english (Быкова) — 8 новых типов, см. подробный разбор в
    // lib/textbookIndex.ts у соответствующих Task-типов.
    case 'word_categorization':
      return task.categories.map((cat, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: `Категория "${cat.name}" (дано: ${cat.given})`,
        knownWordSet: cat.words
      }));
    case 'pluralize_nouns':
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: `${item.count}/${item.noun}`,
        knownWordAnswer: item.answer
      }));
    case 'pronoun_replacement':
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: item.noun,
        knownWordAnswer: item.answer
      }));
    case 'multiple_choice':
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: item.question,
        knownWordAnswer: item.answer
      }));
    case 'verb_form_fill':
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: item.sentence,
        knownWordSequence: item.answer
      }));
    case 'sentence_from_cue':
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: item.cue,
        knownSentence: item.answer
      }));
    case 'question_response_matching':
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: item.question,
        knownWordAnswer: item.answer
      }));
    case 'odd_one_out':
      return task.items.map((item, i) => ({
        id: `${task.number}${letterFor(i)}`,
        displayCondition: item.words.join(', '),
        knownWordAnswer: item.answer
      }));
    // 02.09.2026: русский язык, Канакина — "Спишите [заданный текст]".
    // Один item на весь task (не массив items — тут одно задание = один
    // текст для копирования). Переиспользует уже существующие
    // knownSentence/buildSentenceCheckTask (тот же лояльный word-diff, что
    // и у английского sentence_from_cue) — новый компаратор не нужен.
    case 'copy_text':
      return [
        Array.isArray(task.text)
          ? {
              id: task.number,
              displayCondition: task.text.join(' / '),
              knownSentence: task.text[0],
              knownSentenceOptions: task.text
            }
          : {
              id: task.number,
              displayCondition: task.text,
              knownSentence: task.text
            }
      ];
    default:
      return [];
  }
}

type IndexMatch = { candidate: HintTaskCandidate; entry: IndexEntry; items: NarrowItem[] };
type IndexMatchResult = { ok: true; matches: IndexMatch[] } | { ok: false; reason: string };

// Строже банковского порога 0.6 (см. matchScore/MATCH_THRESHOLD выше в
// этом файле) — здесь цена ложного срабатывания выше: неверный матч
// значит показать ребёнку чужую подсказку под видом его задания.
const INDEX_MATCH_THRESHOLD = 0.7;
const INDEX_MATCH_TIE_EPSILON = 0.05;

function symmetricMatchScore(a: string[], b: string[]): number {
  if (a.length === 0 || b.length === 0) return 0;
  return Math.max(matchScore(a, b), matchScore(b, a));
}

// 21.08.2026: текстовое сходство подводит, когда на фото нет печатного
// условия вообще (решение в обычной тетради, не в рабочей тетради/учебнике)
// — реальный кейс: ребёнок пишет и условие, и примеры СВОИМИ словами/без
// подписей ("Было-75 п. Вышли-25 п.", или просто "76+18=94" без заголовка
// "Вычисли и проверь решение."), почти не пересекаясь по словам с
// печатным текстом задания в индексе (проверено на реальном фото, см.
// CLAUDE.md). Числа при этом обычно совпадают почти дословно — используем
// их как ВТОРОЙ, независимый сигнал сопоставления (механическая сверка
// чисел, тот же принцип "не доверяй тексту/суждению модели, сверяй факты",
// что и везде в проекте).
//
// ОДНОНАПРАВЛЕННО (только "все числа задачи нашлись у ребёнка", не
// наоборот) — намеренно: candidate почти всегда содержит ЛИШНИЕ числа
// помимо операндов условия (ребёнок дописывает результат: "76+18=94" даёт
// 76,18,94, а в условии есть только 76,18) — требовать совпадения и в
// обратную сторону систематически занижало бы честный матч. Риск
// ложного совпадения при этом невысок: candidate уже сужен до координат
// ОДНОГО задания самим детектом, не вся страница целиком.
function extractNumbers(text: string): number[] {
  return ((text || '').match(/\d+/g) || []).map(Number);
}

function numericFingerprintScore(candidateNumbers: number[], targetNumbers: number[]): number {
  if (candidateNumbers.length === 0 || targetNumbers.length === 0) return 0;
  const candidateSet = new Set(candidateNumbers);
  const targetSet = new Set(targetNumbers);
  const found = [...targetSet].filter((n) => candidateSet.has(n)).length;
  return found / targetSet.size;
}

// Числа, "зашитые" в условие задачи в индексе — по одному варианту
// извлечения на answerType (только операнды/данные условия, БЕЗ уже
// готового ответа — см. комментарий выше про лишние числа).
function numbersFingerprintForEntry(entry: IndexEntry): number[] {
  const { task } = entry;
  switch (task.answerType) {
    case 'computation_list':
      return task.items.flatMap((item) => extractNumbers(item.expression));
    case 'equations':
      return task.items.flatMap((item) => extractNumbers(item.equation));
    case 'fill_blank_equation':
      return task.items.flatMap((item) => extractNumbers(item.expression_template));
    case 'chain':
      return task.items.flatMap((item) => [item.start, ...extractNumbers(item.steps.join(' '))]);
    case 'word_problem':
      return extractNumbers(task.prompt);
    case 'word_problems':
      return extractNumbers(task.items.map((i) => i.condition).join(' '));
    case 'number_sequence':
      // 28.08.2026: пилот Петерсон — числа самого данного ряда (НЕ ответ,
      // та же логика "без готового ответа", что и у остальных типов выше).
      return task.items.flatMap((item) => item.given);
    case 'function_table':
      // 28.08.2026: только inputs (уже напечатаны в условии, до заполнения
      // ребёнком) — outputs сознательно не включены сюда: это как раз то,
      // что ребёнок ещё допишет, тот же принцип "без готового ответа", что
      // и у остальных типов выше.
      return task.tables.flatMap((t) => t.inputs);
    // 01.09.2026: english (Быкова) — только "count" уже напечатан в
    // условии ("2/table" — "2" дано, "tables" ребёнок дописывает).
    case 'pluralize_nouns':
      return task.items.map((item) => item.count);
    default:
      return [];
  }
}

// 22.08.2026: текст для ТЕКСТОВОГО сопоставления обычно — task.prompt (сама
// инструкция задания). Но для copy_and_mark_grammar инструкция короткая и
// не содержит слов из самого текста, который нужно распознать на фото
// ("Спишите. Проверьте себя..." — ни одного общего слова с "Прекрасное и
// удивительное слово..."), поэтому для этого типа сопоставляем с
// известным ПОЛНЫМ текстом (task.text), а не с инструкцией.
//
// 23.08.2026: реальный прод-кейс — та же проблема у fill_blank_word.
// task.prompt там тоже общая инструкция ("Прочитайте загадки. Отгадайте
// их. Выпишите...") — ни одного слова из того, что ребёнок реально пишет
// ("Реснички какие? белые, корзинка какая? белая..."). На фото решения
// в отдельной тетради (без печатного текста самого задания вообще) это
// означало, что сопоставить было НЕ ПО ЧЕМУ — ни по номеру (на фото не
// было написано "№153"), ни по тексту (сравнивали не с тем). Строим
// текст для сопоставления из самих noun+question+answer — то, что
// реально пишет ребёнок, слово в слово.
function matchTextForEntry(entry: IndexEntry): string {
  const { task } = entry;
  if (task.answerType === 'copy_and_mark_grammar') return task.text;
  if (task.answerType === 'fill_blank_word') {
    return task.items.map((item) => `${item.noun} ${item.question} ${item.answer}`).join(' ');
  }
  // 28.08.2026: пилот Петерсон — та же причина, что и у fill_blank_word
  // выше: на "голой" странице решения ребёнок пишет только базовое слово
  // и свой ответ, а не полную инструкцию задания, поэтому сопоставляем по
  // самим словам, а не по task.prompt.
  if (task.answerType === 'word_formation') {
    return task.items.map((item) => `${item.base} ${item.insert || ''} ${item.replace_to || ''} ${item.answer}`).join(' ');
  }
  // 01.09.2026: english (Быкова) — та же причина, что и у fill_blank_word/
  // word_formation выше: инструкция задания ("Вставь am, is, are") не
  // содержит слов, которые реально напечатаны на странице (сами
  // предложения/слова/варианты). Сопоставляем по печатному содержанию.
  if (task.answerType === 'word_categorization') {
    return task.categories.map((cat) => `${cat.name} ${cat.given} ${cat.words.join(' ')}`).join(' ');
  }
  if (task.answerType === 'pluralize_nouns') {
    return task.items.map((item) => `${item.count} ${item.noun}`).join(' ');
  }
  if (task.answerType === 'pronoun_replacement') {
    return task.items.map((item) => item.noun).join(' ');
  }
  if (task.answerType === 'multiple_choice') {
    return task.items.map((item) => `${item.question} ${Object.values(item.options).join(' ')}`).join(' ');
  }
  if (task.answerType === 'verb_form_fill') {
    return task.items.map((item) => item.sentence).join(' ');
  }
  if (task.answerType === 'sentence_from_cue') {
    return task.items.map((item) => item.cue).join(' ');
  }
  if (task.answerType === 'question_response_matching') {
    return task.items.map((item) => item.question).join(' ') + ' ' + Object.values(task.options).join(' ');
  }
  if (task.answerType === 'odd_one_out') {
    return task.items.map((item) => item.words.join(' ')).join(' ');
  }
  if (task.answerType === 'copy_text') {
    // 02.09.2026: та же причина, что и у copy_and_mark_grammar выше —
    // инструкция ("Спишите. Проверьте себя.") не пересекается по словам с
    // самим текстом, который нужно распознать на фото решения.
    // 03.09.2026: text может быть массивом вариантов ("спишите ЛЮБОЕ
    // четверостишие") — для текстового сопоставления кандидата с фото
    // объединяем все варианты, ребёнок мог списать любой из них.
    return Array.isArray(task.text) ? task.text.join(' ') : task.text;
  }
  return task.prompt;
}

// 22.08.2026: реальный прод-кейс — когда единственный кандидат на фото
// получил номер от detectSolutionTaskNumber() (отдельная, уже проверенная
// функция специально для чтения "Упр. N"/"№N" — см. CLAUDE.md, «Сверка
// номера задания»), сам номер — уже сильный независимый сигнал. Требовать
// ДОПОЛНИТЕЛЬНО высокое текстовое сходство поверх него избыточно строго:
// для задач вроде copy_and_mark_grammar (целый переписанный абзац) детект
// границ задания транскрибирует текст с ошибками (путает отдельные слова),
// которые не мешают самой узкой проверке ниже (она сверяет текст заново,
// откалиброванным промптом), но систематически занижают score схожести.
// Используется ТОЛЬКО когда для номера в индексе есть РОВНО ОДНА запись
// (без двусмысленности — не нужно ничего выбирать) — иначе безопасно
// возвращает null, и вызывающий код падает обратно на обычное
// сопоставление (matchCandidatesToIndex) с его текстовым/числовым score.
function tryDirectNumberMatch(candidate: HintTaskCandidate, number: string, subject: Subject): IndexMatch | null {
  // 03.09.2026: фильтр по предмету ДО проверки "ровно одна запись" — см.
  // комментарий у IndexEntry в lib/textbookIndex.ts про реальный прод-баг
  // с ложным межпредметным совпадением по номеру.
  const entries = findIndexEntriesByNumber(number).filter((e) => e.subject === subject);
  if (entries.length !== 1) return null;
  const entry = entries[0];
  if (!WHITELISTED_ANSWER_TYPES.has(entry.task.answerType)) return null;
  const items = buildNarrowItems(entry);
  if (items.length === 0) return null;
  return { candidate, entry, items };
}

// 23.08.2026: реальный прод-кейс — рукописный номер задания ("Упр. 159")
// читается ненадёжно (то "1", то "150", то вовсе не находится) — само
// сопоставление ПО НОМЕРУ на "голых" страницах в принципе шаткое звено.
// По прямому предложению владельца — ищем СРАЗУ по содержанию, во ВСЁМ
// индексе (не только среди записей с угаданным номером), используя тот
// же текстовый score, что и обычное сопоставление, но БЕЗ зависимости от
// номера вообще. Порог строже обычного (0.5 вместо обычных 0.7 у
// текстового сигнала, см. matchCandidatesToIndex) — компенсируем тем, что
// здесь сравниваем не короткую строку, а обычно длинный кусок связного
// текста, где даже частичное совпадение уже достаточно уверенно указывает
// на конкретное задание (случайное совпадение целого абзаца с чужим
// заданием практически невозможно). Тай-брейк (secondBest) обязателен —
// два похожих по содержанию задания не должны молча выбрать первое.
const TEXT_CONTENT_MATCH_THRESHOLD = 0.5;
const TEXT_CONTENT_TIE_EPSILON = 0.05;

function findEntryByTextContent(candidateCondition: string, subject: Subject): IndexEntry | null {
  const conditionWords = normalizeWords(candidateCondition);
  if (conditionWords.length === 0) return null;

  // 03.09.2026: фильтр по предмету — см. комментарий у IndexEntry в
  // lib/textbookIndex.ts про реальный прод-баг с ложным межпредметным
  // совпадением (русский текст сопоставился с английским заданием).
  const scored = getAllIndexEntries()
    .filter((entry) => entry.subject === subject && WHITELISTED_ANSWER_TYPES.has(entry.task.answerType))
    .map((entry) => ({ entry, score: symmetricMatchScore(conditionWords, normalizeWords(matchTextForEntry(entry))) }))
    .sort((a, b) => b.score - a.score);

  const best = scored[0];
  const secondBest = scored[1];
  if (!best || best.score < TEXT_CONTENT_MATCH_THRESHOLD) return null;
  if (secondBest && best.score - secondBest.score < TEXT_CONTENT_TIE_EPSILON) return null;
  return best.entry;
}

// Чистый код, без вызова модели — сопоставляет то, что уже нашёл
// detectTasksOnTaskPhoto (номер + короткий текст рядом с заданием), с
// известным индексом. Номера НЕ уникальны глобально (нумерация начинается
// заново на границе раздела учебника), поэтому сопоставляем по связке
// номер + текст/числа, а не по одному номеру — см. lib/textbookIndex.ts.
//
// Итоговый score — максимум из текстового сходства и числового отпечатка
// (см. numericFingerprintScore выше) — оба сигнала независимы, побеждает
// более уверенный. Числовой сигнал считается для ВСЕХ whitelisted-типов
// (не только текстовых задач) — на странице без печатного текста
// текстовое сходство ненадёжно вообще для любого типа задания, не только
// для word_problem.
// 02.09.2026: реальный прод-кейс на english (Быкова) — DETECT_TASKS_PROMPT
// явно просит буквенные подпункты вида "11а"/"11б" (см. текст промпта в
// lib/claude.ts), но на странице с построчно пронумерованными предложениями
// (задание 11: "1. I/a radio", "2. I/a cat"...) модель вместо этого иногда
// возвращает ДЕСЯТИЧНУЮ вложенность — как САМ родительский номер "11"
// (условие = общая инструкция упражнения целиком, дублирует область детей),
// ТАК И детей "11.1".."11.7" (условие = реально напечатанная строка). Не
// трогаем сам DETECT_TASKS_PROMPT (риск регрессии для math/russian, где
// такой формат не наблюдался, см. комментарий у detectHandwrittenTasksOnSolutionPhoto
// в этом же файле про цену правок в общих промптах) — вместо этого чистим
// РЕЗУЛЬТАТ детекта: (1) отбрасываем родительский "контейнер" (его номер
// совпадает с префиксом хотя бы одного desyatichного ребёнка — он ничего
// не добавляет, кроме дублирующей общей инструкции, которая не может
// сопоставиться ни с чем в индексе, если задания разнесены на отдельные
// записи по реальному номеру строки, см. bykova JSON restructureNote);
// (2) для оставшихся десятичных детей номер для сопоставления — ПОСЛЕДНИЙ
// сегмент (сама строка), а не первый (контекст родителя).
function flattenDottedCandidates(candidates: HintTaskCandidate[]): HintTaskCandidate[] {
  const dotted = candidates.filter((c) => /^\d+\.\d+$/.test(c.number));
  if (dotted.length === 0) return candidates;
  const parentPrefixes = new Set(dotted.map((c) => c.number.split('.')[0]));
  return candidates
    .filter((c) => !parentPrefixes.has(c.number))
    .map((c) => (/^\d+\.\d+$/.test(c.number) ? { ...c, number: c.number.split('.').pop()! } : c));
}

function matchCandidatesToIndex(rawCandidates: HintTaskCandidate[], subject: Subject): IndexMatchResult {
  const candidates = flattenDottedCandidates(rawCandidates);
  if (candidates.length === 0) return { ok: false, reason: 'no_candidates' };

  const matches: IndexMatch[] = [];
  for (const candidate of candidates) {
    // /\d+/ без ^ — а не только "цифры в начале строки" — потому что
    // детект иногда возвращает номер с префиксом вида "№4" (реальный
    // случай на фото без печатной нумерации, только рукописное "№4" перед
    // решением), не только суффиксом вида "9a".
    const baseNumber = candidate.number.match(/\d+/)?.[0] || candidate.number;
    // 03.09.2026: фильтр по предмету ДО скоринга — реальный прод-баг:
    // рукописное "Упр.12" (русский язык, текст про соловья) ложно
    // совпало с английским заданием Быковой ("12/glass") просто потому,
    // что оба содержат число 12 — numericFingerprintScore(candidateNumbers,
    // [12]) дал идеальные 1.0 для СОВЕРШЕННО постороннего задания другого
    // предмета/языка/учебника, а findIndexEntriesByNumber искал по ВСЕМ
    // книгам сразу. См. комментарий у IndexEntry в lib/textbookIndex.ts.
    const entries = findIndexEntriesByNumber(baseNumber).filter((e) => e.subject === subject);
    if (entries.length === 0) return { ok: false, reason: `no_index_entry_for_number_${candidate.number}` };

    const conditionWords = normalizeWords(candidate.condition);
    const candidateNumbers = extractNumbers(candidate.condition);
    const scored = entries
      .map((entry) => {
        const textScore = symmetricMatchScore(conditionWords, normalizeWords(matchTextForEntry(entry)));
        const numericScore = numericFingerprintScore(candidateNumbers, numbersFingerprintForEntry(entry));
        return { entry, score: Math.max(textScore, numericScore) };
      })
      .sort((a, b) => b.score - a.score);

    const best = scored[0];
    const secondBest = scored[1];
    if (process.env.DEBUG_INDEX_MATCH) {
      console.log(
        `[DEBUG] candidate "${candidate.number}" cond="${candidate.condition}" best=${best?.score.toFixed(2)} entry="${best ? matchTextForEntry(best.entry) : ''}" second=${secondBest?.score.toFixed(2)}`
      );
    }
    if (!best || best.score < INDEX_MATCH_THRESHOLD) {
      return { ok: false, reason: `low_match_score_${candidate.number}` };
    }
    if (secondBest && best.score - secondBest.score < INDEX_MATCH_TIE_EPSILON) {
      return { ok: false, reason: `ambiguous_match_${candidate.number}` };
    }
    if (!WHITELISTED_ANSWER_TYPES.has(best.entry.task.answerType)) {
      return { ok: false, reason: `unsupported_answer_type_${best.entry.task.answerType}` };
    }

    const items = buildNarrowItems(best.entry);
    if (items.length === 0) return { ok: false, reason: `no_narrow_items_${candidate.number}` };
    matches.push({ candidate, entry: best.entry, items });
  }
  return { ok: true, matches };
}

