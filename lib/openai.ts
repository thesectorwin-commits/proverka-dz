function normalizeNumericAnswer(raw: string | null | undefined): number | null {
  if (raw == null) return null;
  const cleaned = String(raw).trim().replace(/\s+/g, '').replace(/,/g, '.');
  if (!/^-?\d+(\.\d+)?$/.test(cleaned)) return null;
  const n = parseFloat(cleaned);
  return Number.isNaN(n) ? null : n;
}

// 21.08.2026: для word_problem/word_problems — не читаем от модели, как
// именно записаны промежуточные шаги (это ещё один вызов и ещё один риск
// контаминации, см. историю многошаговой арифметики в CLAUDE.md), сверяем
// в коде только ФИНАЛЬНЫЙ ответ. Если он неверный — подсказка перечисляет
// НАЗВАНИЯ шагов задачи (что нужно посчитать на каждом), но НИ ОДНОГО
// числа не называет — тот же принцип, что и у buildDigitPlaceHint.
function buildStepsHint(steps: { description: string }[] | undefined): string {
  if (!steps || steps.length === 0) {
    return 'Ответ записан неверно — реши задачу ещё раз, внимательно перечитав условие.';
  }
  const stepList = steps.map((s, i) => `${i + 1}) ${s.description}`).join(', ');
  return `Ответ записан неверно. Реши задачу по действиям и сверь каждое: ${stepList}. Найди, на каком действии закралась ошибка.`;
}

// 22.08.2026: разбор одной дословно распознанной строки вида "76+18=94" —
// левая часть (само выражение, как написано) + правая часть (число после
// "="). Используется ТОЛЬКО для requiresCheck-заданий (см.
// buildIndexCheckTaskWithVerification ниже) — не заменяет обычный путь
// "written_answer" для остальных заданий.
function parseWrittenLine(line: string): { leftExpr: string; rightValue: number } | null {
  const idx = line.indexOf('=');
  if (idx === -1) return null;
  const leftExpr = line.slice(0, idx).trim();
  const rightValue = normalizeNumericAnswer(line.slice(idx + 1));
  if (rightValue === null) return null;
  return { leftExpr, rightValue };
}

function normalizeExpressionForCompare(expr: string): string {
  return (expr || '').replace(/\s+/g, '').replace(/[−‐‑‒–—]/g, '-');
}

// 22.08.2026: реальный прод-кейс — узкий вопрос "верни числа после = в
// проверочных равенствах" оказался ненадёжным (см. комментарий у
// buildIndexNarrowVerificationPrompt). По совету внешней модели (GPT) —
// вместо этого модель дословно переписывает ВЕСЬ блок строк примера
// целиком ("lines"), а строку с САМИМ примером код находит сам (сравнивая
// левую часть каждой строки с уже известным hintExpression) — модели не
// нужно самой ЗНАТЬ, какая строка "главная", только честно всё
// перечислить. Остальные строки блока — проверочные равенства, их числа
// после "=" сверяются с item.checkEquations (см. buildCheckEquationSpecs).
//
// 02.09.2026: реальный прод-кейс — раньше эта функция возвращала ОДИН
// CheckTask на весь item, сворачивая проверку решения внутрь его статуса
// (родитель видел только "4 примера", хотя ребёнок физически написал 12
// равенств — основной пример + 2 проверочных на каждый). По прямому
// запросу владельца, для единообразия с обычным (не-индексным) пайплайном
// (там каждое равенство — свой видимый пункт), возвращаем МАССИВ: основной
// пример + отдельный пункт на КАЖДОЕ проверочное равенство, с его
// собственным текстом ("94 - 18 = ?"), а не общей фразой "проверка".
// Ограничение: сверяем ТОЛЬКО по числу-результату (как и раньше), не по
// тому, какую именно из двух строк ребёнок написал первой — если он
// написал оба проверочных равенства, но перепутал их порядок, это не
// считается ошибкой (порядок строк в задании не оговорён).
function buildIndexCheckTaskWithVerification(item: NarrowItem, writtenLines: string[] | undefined): CheckTask[] {
  const parsedLines = (writtenLines || [])
    .map(parseWrittenLine)
    .filter((p): p is { leftExpr: string; rightValue: number } => p !== null);

  const targetExpr = normalizeExpressionForCompare(item.hintExpression || '');
  const mainLineIndex = parsedLines.findIndex((p) => normalizeExpressionForCompare(p.leftExpr) === targetExpr);

  if (mainLineIndex === -1) {
    return [
      {
        number: item.id,
        condition: item.displayCondition,
        status: 'unclear',
        explanation: 'Не удалось разобрать написанный ответ — сверьте вместе со взрослым.',
        correct_solution: ''
      }
    ];
  }

  const writtenAnswer = parsedLines[mainLineIndex].rightValue;
  const isCorrect = writtenAnswer === item.knownAnswer;
  const mainTask: CheckTask = isCorrect
    ? { number: item.id, condition: item.displayCondition, status: 'correct', explanation: '', correct_solution: String(item.knownAnswer) }
    : {
        number: item.id,
        condition: item.displayCondition,
        status: 'incorrect',
        explanation: buildDigitPlaceHint(item.hintExpression, String(writtenAnswer)),
        correct_solution: ''
      };

  if (!item.checkEquations || item.checkEquations.length === 0) {
    return [mainTask];
  }

  // Основной пример неверен — проверочные равенства всё равно физически
  // написаны на фото, но их обсуждать бессмысленно, пока не исправлен сам
  // пример: показываем их как "unclear" с понятным объяснением, а не молча
  // пропускаем (иначе родитель снова увидит меньше пунктов, чем написано).
  if (!isCorrect) {
    const skippedChecks: CheckTask[] = item.checkEquations.map((eq) => ({
      number: `${item.id}-check-${eq.expected}`,
      condition: eq.condition,
      status: 'unclear',
      explanation: 'Сначала исправь сам пример выше — проверка имеет смысл только для верного ответа.',
      correct_solution: ''
    }));
    return [mainTask, ...skippedChecks];
  }

  const writtenChecks = parsedLines.filter((_, i) => i !== mainLineIndex).map((p) => p.rightValue);
  const writtenSet = new Set(writtenChecks);

  const checkTasks: CheckTask[] = item.checkEquations.map((eq) => {
    const found = writtenSet.has(eq.expected);
    return {
      number: `${item.id}-check-${eq.expected}`,
      condition: eq.condition,
      status: found ? 'correct' : 'incorrect',
      explanation: found
        ? ''
        : writtenChecks.length === 0
        ? 'Проверка решения не выполнена — допиши это равенство, как требует задание.'
        : 'Это проверочное равенство не найдено или посчитано неверно — пересчитай его ещё раз.',
      correct_solution: found ? String(eq.expected) : ''
    };
  });

  return [mainTask, ...checkTasks];
}

// 22.08.2026: первый предмет кроме математики (русский язык, fill_blank_word) —
// сравнение ОДНОГО слова, а не числа. Регистронезависимо + ё→е (частая
// орфографическая замена от руки) — иначе "жолтый"/"жёлтый" ложно считались
// бы разными словами.
function normalizeWordAnswer(raw: string | null | undefined): string | null {
  if (raw == null) return null;
  const cleaned = String(raw)
    .trim()
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[.,!?;:"'«»()]/g, '')
    .trim();
  return cleaned || null;
}

function buildWordCheckTask(item: NarrowItem, writtenRaw: string | null | undefined): CheckTask {
  const written = normalizeWordAnswer(writtenRaw);
  if (written === null) {
    return {
      number: item.id,
      condition: item.displayCondition,
      status: 'unclear',
      explanation: 'Не получилось разобрать написанный ответ — сверьте вместе со взрослым.',
      correct_solution: ''
    };
  }

  const isCorrect = written === normalizeWordAnswer(item.knownWordAnswer);
  return {
    number: item.id,
    condition: item.displayCondition,
    status: isCorrect ? 'correct' : 'incorrect',
    // Не называем верное слово при ошибке — только указываем, где искать
    // (тот же принцип, что и у buildDigitPlaceHint/buildStepsHint выше).
    // 03.09.2026: раньше текст был жёстко зашит под ОДИН конкретный тип
    // задания ("сверься с текстом загадки") — но knownWordAnswer общий
    // для множества разных answerType (геометрические термины Петерсон,
    // словообразование, английские упражнения и т.д.), где никакой
    // загадки нет и в помине — нашлось при разборе реального прод-кейса,
    // где эта формулировка попала в результат по совсем не-загадочному
    // заданию. Текст сделан нейтральным, без предположений об источнике.
    explanation: isCorrect
      ? ''
      : item.hintQuestion
        ? `Ответ записан неверно — перечитай условие и найди ответ на вопрос «${item.hintQuestion}».`
        : 'Ответ записан неверно — перечитай условие ещё раз и попробуй снова.',
    correct_solution: isCorrect ? item.knownWordAnswer || '' : ''
  };
}

// 22.08.2026: только "ед"/"мн" как различитель — модель может написать
// "ед.ч", "ед.ч.", "единственное число" и т.п., все варианты содержат
// характерный корень.
function normalizeGrammarLabel(raw: string | null | undefined): 'ед' | 'мн' | null {
  if (!raw) return null;
  const s = raw.toLowerCase();
  if (s.includes('ед')) return 'ед';
  if (s.includes('мн')) return 'мн';
  return null;
}

// 22.08.2026: реальный прод-тест показал, что просить модель саму
// вынести вердикт "text_copied_correctly": true/false + сочинить цитату
// расхождения ненадёжно даже с калиброванным промптом ("требуй цитату" +
// "при неуверенности считай верным") — модель дважды процитировала
// расхождение, которого физически нет ни в тексте, ни на фото (чистая
// галлюцинация). Спросили внешнюю модель (GPT) за рекомендациями — совет:
// убрать true/false и цитату из модели ПОЛНОСТЬЮ, оставить ей только
// дословную транскрипцию (см. verifyCopyAndMarkTask ниже), а сравнение с
// известным текстом делает код (diffWords) — модель физически не может
// сочинить цитату несуществующего расхождения, если она вообще не
// формулирует, "совпадает ли" текст, только распознаёт его.
// 22.08.2026: реальный прод-кейс — дефис/тире полностью УДАЛЯЕМ (не
// заменяем на пробел), а не оставляем как символ внутри токена. У одного
// и того же символа "-" на фото два разных смысла: разделитель между
// словами ("слово — мама", с пробелами вокруг) или перенос слова по
// слогам на конце строки ("удивитель-ное", без пробелов) — во ВТОРОМ
// случае модель-транскрайбер иногда сохраняет дефис как есть, и слово
// перестаёт дословно совпадать с эталоном ("удивитель-ное" ≠
// "удивительное"), хотя ребёнок написал его правильно. Полное удаление
// (не замена на пробел) корректно обрабатывает оба случая одновременно.
function tokenizeForDiff(text: string): string[] {
  return (text || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[—–-]/g, '')
    .replace(/[.,!?;:"'«»()]/g, '')
    .split(/\s+/)
    .filter(Boolean);
}

// Простой LCS-diff по словам (стандартный алгоритм наибольшей общей
// подпоследовательности) — находит слова эталона, для которых не нашлось
// соответствия в тексте ученика (пропущено/заменено), и слова у ученика,
// которых нет в эталоне (лишнее/тоже заменено), с учётом порядка слов.
function diffWords(expected: string[], actual: string[]): { missingFromExpected: string[]; extraInActual: string[] } {
  const n = expected.length;
  const m = actual.length;
  const dp: number[][] = Array.from({ length: n + 1 }, () => new Array(m + 1).fill(0));
  for (let i = 1; i <= n; i++) {
    for (let j = 1; j <= m; j++) {
      dp[i][j] = expected[i - 1] === actual[j - 1] ? dp[i - 1][j - 1] + 1 : Math.max(dp[i - 1][j], dp[i][j - 1]);
    }
  }
  const matchedExpectedIdx = new Set<number>();
  const matchedActualIdx = new Set<number>();
  let i = n;
  let j = m;
  while (i > 0 && j > 0) {
    if (expected[i - 1] === actual[j - 1]) {
      matchedExpectedIdx.add(i - 1);
      matchedActualIdx.add(j - 1);
      i--;
      j--;
    } else if (dp[i - 1][j] >= dp[i][j - 1]) {
      i--;
    } else {
      j--;
    }
  }
  return {
    missingFromExpected: expected.filter((_, idx) => !matchedExpectedIdx.has(idx)),
    extraInActual: actual.filter((_, idx) => !matchedActualIdx.has(idx))
  };
}

// 22.08.2026: реальный прод-кейс — LCS-diff показал "слово"/"мама"
// пропущены, а "словомама" лишнее, хотя ребёнок написал верно: модель
// иногда транскрибирует два соседних слова БЕЗ пробела между ними (сам
// разделитель — тире "слово — мама" — не всегда чётко виден на фото).
// Чиним ТОЛЬКО этот конкретный, узкий случай: если токен ученика в
// точности равен конкатенации ДВУХ СОСЕДНИХ слов эталона — считаем, что
// это склейка при распознавании, а не реальная ошибка, и разбиваем токен
// обратно на эти два слова. Не пытается угадывать ничего более общего.
function repairMergedWords(expected: string[], actual: string[]): string[] {
  const repaired: string[] = [];
  for (const token of actual) {
    let wasSplit = false;
    for (let i = 0; i < expected.length - 1; i++) {
      if (expected[i] + expected[i + 1] === token) {
        repaired.push(expected[i], expected[i + 1]);
        wasSplit = true;
        break;
      }
    }
    if (!wasSplit) repaired.push(token);
  }
  return repaired;
}

function splitIntoSentences(text: string): string[] {
  return (text || '')
    .split(/(?<=[.!?])\s+/)
    .map((s) => s.trim())
    .filter(Boolean);
}

// Какие предложения эталона содержат хотя бы одно из пропущенных слов —
// именно ИХ, а не весь текст заново, стоит перепроверить отдельным
// точечным вызовом (см. recheckSentences).
function findSuspiciousSentences(knownText: string, missingWords: string[]): string[] {
  if (missingWords.length === 0) return [];
  const missingSet = new Set(missingWords);
  return splitIntoSentences(knownText).filter((s) => tokenizeForDiff(s).some((w) => missingSet.has(w)));
}

type CopyAndMarkOcrResult = {
  student_text?: string;
  adjective_labels?: Array<{ word: string; written_number: string | null }>;
};

// 22.08.2026: точечный recheck подозрительных предложений — по совету
// внешней модели (GPT), после того как первая (полная) транскрипция дала
// расхождение. НЕ пересылает фото заново целиком с тем же общим вопросом
// (это уже пробовали — иногда OCR на сложных участках нестабилен от
// прогона к прогону) — вместо этого называет модели КОНКРЕТНЫЕ фразы,
// которые нужно перечитать внимательнее, одним батч-вызовом (не по одной
// фразе за вызов — дороже, а обычно расхождение сосредоточено в 1
// предложении). Модель по-прежнему только транскрибирует, не сравнивает —
// финальное решение "совпало ли теперь" считает код (тот же diffWords).
async function recheckSentences(
  image: ImageInput,
  sentences: string[]
): Promise<{ texts: string[]; tokensInput: number; tokensOutput: number }> {
  const list = sentences.map((s, i) => `${i + 1}) "${s}"`).join('\n');
  const promptText = `На фото — рукописный текст ученика. Мы уже распознали большую часть текста, но не уверены ТОЧНО в следующих фразах (они где-то среди уже переписанного текста, каждая — одно из предложений):
${list}

Внимательно найди на фото КАЖДУЮ из этих фраз (по смыслу и расположению — это то же самое место в тексте, даже если у нас распознано неточно) и дословно перепиши, что там ФИЗИЧЕСКИ написано. Не подгоняй под то, что здесь указано как ожидаемое — если видишь другое написание, значит именно так и есть, пиши как видишь.

Ответь строго JSON, без markdown: {"rechecked": ["...", "..."]} — по одной строке на каждую фразу выше, в том же порядке.`;

  const { parsed, tokensInput, tokensOutput } = await callOpenAIResponsesJsonWithRetry(
    {
      model: MODEL,
      reasoning: { effort: 'none' },
      input: [{ role: 'user', content: [{ type: 'input_text', text: promptText }, toImageBlock(image)] }]
    },
    (text) => extractJson(text) as { rechecked?: string[] }
  );

  return { texts: parsed?.rechecked || [], tokensInput, tokensOutput };
}

// 22.08.2026: реальный прод-кейс — "лишние" токены (extraInActual) сами
// по себе НЕ считаем ошибкой ребёнка: они почти всегда шум транскрипции
// (артефакт склейки/разбора), а не то, что ребёнок реально дописал лишнее.
// Итоговый статус зависит ТОЛЬКО от missingFromExpected (все ли ожидаемые
// слова физически нашлись, в правильном порядке) — асимметрия рисков та
// же, что и everywhere в проекте: ложное "неверно" на реально верной
// работе хуже, чем один раз не поймать безобидный лишний токен.
// 23.08.2026: вынесено из buildCopyAndMarkCheckTask в отдельную чистую
// функцию — нужна ДВАЖДЫ (до и после точечного recheck меток, см.
// recheckAdjectiveLabels/verifyCopyAndMarkTask), а не только один раз при
// сборке финальной CheckTask.
function evaluateAdjectiveLabels(
  knownAdjectives: { word: string; number: string }[],
  labels: Array<{ word: string; written_number: string | null }>
): { wrongWords: string[]; missingWords: string[] } {
  const wrongWords: string[] = [];
  const missingWords: string[] = [];
  for (const adj of knownAdjectives) {
    const found = labels.find((a) => normalizeWordAnswer(a.word) === normalizeWordAnswer(adj.word));
    const writtenLabel = normalizeGrammarLabel(found?.written_number);
    if (writtenLabel === null) {
      missingWords.push(adj.word);
    } else if (writtenLabel !== normalizeGrammarLabel(adj.number)) {
      wrongWords.push(adj.word);
    }
  }
  return { wrongWords, missingWords };
}

function buildCopyAndMarkCheckTask(
  item: NarrowItem,
  ocr: CopyAndMarkOcrResult | undefined,
  missingFromExpected: string[],
  wrongWords: string[],
  missingWords: string[]
): CheckTask {
  if (!ocr || !ocr.student_text) {
    return {
      number: item.id,
      condition: item.displayCondition,
      status: 'unclear',
      explanation: 'Не получилось разобрать написанное — сверьте вместе со взрослым.',
      correct_solution: ''
    };
  }

  if (missingFromExpected.length > 0) {
    return {
      number: item.id,
      condition: item.displayCondition,
      status: 'incorrect',
      explanation: `Текст переписан не полностью или с отличием от учебника (пропущено или изменено: "${missingFromExpected.join(
        ', '
      )}") — сверься с ним ещё раз.`,
      correct_solution: ''
    };
  }

  // 23.08.2026: реальный кейс — явно НЕВЕРНО указанная метка (нашли, но не
  // совпадает с ожидаемой) и метка, которую так и НЕ НАШЛИ даже после
  // точечного recheck — разные по силе сигналы. Первое — реальная,
  // вероятная ошибка ребёнка ИЛИ надёжно прочитанное несовпадение;
  // второе — модель просто не смогла прочитать пометку (может, её и нет,
  // а может, неразборчиво) — не хотим ложно отклонять реально верную
  // работу только потому, что мы не смогли её проверить (по совету GPT).
  if (wrongWords.length > 0) {
    return {
      number: item.id,
      condition: item.displayCondition,
      status: 'incorrect',
      explanation: `Текст переписан верно, но число (ед.ч./мн.ч.) над словом${
        wrongWords.length > 1 ? 'ами' : 'ом'
      } "${wrongWords.join('", "')}" указано неверно — проверь ещё раз.`,
      correct_solution: ''
    };
  }

  if (missingWords.length > 0) {
    return {
      number: item.id,
      condition: item.displayCondition,
      status: 'unclear',
      explanation: `Не удалось точно распознать разметку числа над словом${
        missingWords.length > 1 ? 'ами' : 'ом'
      } "${missingWords.join('", "')}" — сверьте вместе со взрослым.`,
      correct_solution: ''
    };
  }

  return {
    number: item.id,
    condition: item.displayCondition,
    status: 'correct',
    explanation: '',
    correct_solution: 'Текст переписан верно, число над прилагательными указано верно.'
  };
}

// 23.08.2026: точечный recheck меток (ед.ч./мн.ч.) — по совету GPT, тот же
// принцип, что и recheckSentences для текста: не пересылать всю страницу
// заново, а назвать модели КОНКРЕТНЫЕ слова, для которых метка не
// нашлась/не распозналась в первом проходе, и попросить перечитать
// внимательнее именно их. Точного кропа "слово + область над ним" сделать
// не можем — координат отдельных слов нет, только координаты всего блока
// текста целиком (см. verifyCopyAndMarkTask) — но узкий, конкретный
// вопрос уже сам по себе снижает нагрузку на модель (тот же эффект, что
// уже помог с recheckSentences без более точного кропа).
async function recheckAdjectiveLabels(
  image: ImageInput,
  words: string[]
): Promise<{ results: Array<{ word: string; written_number: string | null }>; tokensInput: number; tokensOutput: number }> {
  const list = words.map((w) => `"${w}"`).join(', ');
  const promptText = `На фото — рукописный текст ученика, где над некоторыми именами прилагательными подписана рукописная пометка грамматического числа (ед.ч. или мн.ч.). При первом распознавании не удалось надёжно определить эту пометку для следующих слов: ${list}.

Внимательно найди КАЖДОЕ из этих слов в тексте на фото и определи, есть ли НАД НИМ (не под, не рядом — именно над словом) рукописная пометка числа. Не решай сам, какое число ДОЛЖНО быть у этого слова — только распознай, что физически написано, если написано вообще.

Ответь строго JSON, без markdown: {"results": [{"word": "...", "written_number": "ед.ч"}, {"word": "...", "written_number": null}]}`;

  const { parsed, tokensInput, tokensOutput } = await callOpenAIResponsesJsonWithRetry(
    {
      model: MODEL,
      reasoning: { effort: 'none' },
      input: [{ role: 'user', content: [{ type: 'input_text', text: promptText }, toImageBlock(image)] }]
    },
    (text) => extractJson(text) as { results?: Array<{ word: string; written_number: string | null }> }
  );

  return { results: parsed?.results || [], tokensInput, tokensOutput };
}

// 22.08.2026: отдельный, ничем не разбавленный вызов для copy_and_mark_grammar
// (по совету GPT) — модель делает ТОЛЬКО транскрипцию (текст целиком +
// что написано над каждым известным прилагательным), не оценивает
// совпадение и не сочиняет цитату расхождения. Физическая изоляция —
// обрезка по координатам кандидата, если есть (та же cropImageByPercent,
// что и везде в проекте), иначе используется фото целиком. При расхождении
// после первой транскрипции — точечный recheck подозрительных предложений
// (см. recheckSentences), не пересылка всего фото заново и не majority-vote
// из нескольких полных попыток (GPT явно отговаривал от обоих вариантов).
async function verifyCopyAndMarkTask(
  image: ImageInput,
  item: NarrowItem,
  yStartPercent?: number,
  yEndPercent?: number
): Promise<{ task: CheckTask; tokensInput: number; tokensOutput: number }> {
  let focusedImage = image;
  if (yStartPercent != null && yEndPercent != null) {
    const cropped = await cropImageByPercent(image, yStartPercent, yEndPercent);
    if (cropped) focusedImage = cropped;
  }

  let tokensInput = 0;
  let tokensOutput = 0;

  const wordList = (item.knownAdjectives || []).map((a) => `"${a.word}"`).join(', ');
  const promptText = `Перед тобой фотография тетради ученика с домашней работой (обычно сверху дата и подпись "Домашняя работа" или номер упражнения, затем сам переписанный текст, иногда снизу отметка/комментарий учителя). Твоя ЕДИНСТВЕННАЯ задача — дословно распознать ТОЛЬКО связный текст, который ученик переписывал из учебника (это основная часть страницы, обычно несколько полных предложений). НЕ включай в ответ дату, слово "Домашняя работа", номер упражнения ("Упр. N", "№N") и любые пометки/оценки учителя — только сам переписанный связный текст. НЕ проверяй его правильность, НЕ исправляй ошибки, НЕ сравнивай с каким-либо эталоном, НЕ додумывай отсутствующие слова — если слово не видно, просто пропусти его. Сохрани порядок слов и предложений, как они написаны.

Также определи, какое грамматическое число (ед.ч./мн.ч.) ученик подписал НАД каждым из следующих слов, если оно встретится в тексте: ${wordList}. Это тоже только распознавание — не проверяй правильность.

Ответь строго JSON, без markdown:
{"student_text": "весь распознанный текст одной строкой, дословно", "adjective_labels": [{"word": "...", "written_number": "ед.ч"}]}`;

  const { parsed, tokensInput: t1, tokensOutput: o1 } = await callOpenAIResponsesJsonWithRetry(
    {
      model: MODEL,
      reasoning: { effort: 'none' },
      input: [{ role: 'user', content: [{ type: 'input_text', text: promptText }, toImageBlock(focusedImage)] }]
    },
    (text) => extractJson(text) as CopyAndMarkOcrResult
  );
  tokensInput += t1;
  tokensOutput += o1;

  if (!parsed || !parsed.student_text) {
    return { task: buildCopyAndMarkCheckTask(item, parsed || undefined, [], [], []), tokensInput, tokensOutput };
  }

  const expectedWords = tokenizeForDiff(item.knownText || '');
  const actualWords = repairMergedWords(expectedWords, tokenizeForDiff(parsed.student_text));
  let { missingFromExpected } = diffWords(expectedWords, actualWords);

  if (missingFromExpected.length > 0 && item.knownText) {
    const suspicious = findSuspiciousSentences(item.knownText, missingFromExpected);
    if (suspicious.length > 0) {
      const recheck = await recheckSentences(focusedImage, suspicious);
      tokensInput += recheck.tokensInput;
      tokensOutput += recheck.tokensOutput;

      const confirmed = suspicious.every((sentence, i) => {
        const sExpected = tokenizeForDiff(sentence);
        const sActual = repairMergedWords(sExpected, tokenizeForDiff(recheck.texts[i] || ''));
        return diffWords(sExpected, sActual).missingFromExpected.length === 0;
      });

      // Recheck подтвердил ВСЕ подозрительные предложения — значит
      // причина расхождения была в первой (менее внимательной) транскрипции,
      // а не в реальной ошибке ребёнка. Убираем слова этих предложений из
      // итогового списка пропущенных.
      if (confirmed) {
        const confirmedWords = new Set(suspicious.flatMap((s) => tokenizeForDiff(s)));
        missingFromExpected = missingFromExpected.filter((w) => !confirmedWords.has(w));
      }
    }
  }

  // Грамматические метки проверяем ТОЛЬКО если текст уже подтверждён
  // (missingFromExpected пуст) — если текст переписан неверно, задание и
  // так будет "incorrect", доп. recheck меток не нужен.
  let wrongWords: string[] = [];
  let missingWords: string[] = [];
  if (missingFromExpected.length === 0) {
    const evaluated = evaluateAdjectiveLabels(item.knownAdjectives || [], parsed.adjective_labels || []);
    wrongWords = evaluated.wrongWords;
    missingWords = evaluated.missingWords;

    // 23.08.2026: точечный recheck меток (по совету GPT) — если после
    // первого прохода какие-то метки не нашлись/не распознались, называем
    // модели конкретные слова и просим перечитать внимательнее их одних,
    // не всю страницу заново. См. recheckAdjectiveLabels.
    if (missingWords.length > 0) {
      const recheck = await recheckAdjectiveLabels(focusedImage, missingWords);
      tokensInput += recheck.tokensInput;
      tokensOutput += recheck.tokensOutput;

      const mergedLabels = [
        ...(parsed.adjective_labels || []).filter(
          (a) => !missingWords.some((w) => normalizeWordAnswer(w) === normalizeWordAnswer(a.word))
        ),
        ...recheck.results
      ];
      const reEvaluated = evaluateAdjectiveLabels(item.knownAdjectives || [], mergedLabels);
      wrongWords = reEvaluated.wrongWords;
      missingWords = reEvaluated.missingWords;
    }
  }

  return {
    task: buildCopyAndMarkCheckTask(item, parsed, missingFromExpected, wrongWords, missingWords),
    tokensInput,
    tokensOutput
  };
}

// 28.08.2026: пилот Петерсон — сравнение НЕСКОЛЬКИХ чисел по порядку
// (продолжение ряда), а не одного. Переиспользует уже существующий
// extractNumbers() (тот же, что и для числового отпечатка сопоставления
// выше) — просто вытаскивает все числа из written_answer и сравнивает
// массивы поэлементно, порядок важен.
function buildSequenceCheckTask(item: NarrowItem, writtenRaw: string | null | undefined): CheckTask {
  const written = extractNumbers(writtenRaw || '');
  const known = item.knownNumberSequence || [];
  if (written.length === 0) {
    return {
      number: item.id,
      condition: item.displayCondition,
      status: 'unclear',
      explanation: 'Не получилось разобрать написанный ответ — сверьте вместе со взрослым.',
      correct_solution: ''
    };
  }

  const isCorrect = written.length === known.length && known.every((n, i) => n === written[i]);
  return {
    number: item.id,
    condition: item.displayCondition,
    status: isCorrect ? 'correct' : 'incorrect',
    explanation: isCorrect
      ? ''
      : 'Проверь закономерность ряда ещё раз — на сколько каждое следующее число отличается от предыдущего? Примени то же самое действие ещё раз.',
    correct_solution: isCorrect ? known.join(', ') : ''
  };
}

// 01.09.2026: english (Быкова) — verb_form_fill, сравнение слов по
// позициям (аналог buildSequenceCheckTask выше, но для слов, не чисел).
function buildWordSequenceCheckTask(item: NarrowItem, writtenWords: Array<string | null> | undefined): CheckTask {
  const known = item.knownWordSequence || [];
  const written = writtenWords || [];
  if (written.length === 0 || written.every((w) => w == null)) {
    return {
      number: item.id,
      condition: item.displayCondition,
      status: 'unclear',
      explanation: 'Не получилось разобрать написанный ответ — сверьте вместе со взрослым.',
      correct_solution: ''
    };
  }
  const isCorrect =
    written.length === known.length && known.every((w, i) => normalizeWordAnswer(written[i]) === normalizeWordAnswer(w));
  return {
    number: item.id,
    condition: item.displayCondition,
    status: isCorrect ? 'correct' : 'incorrect',
    explanation: isCorrect
      ? ''
      : 'Проверь форму глагола ещё раз — вспомни, с каким подлежащим (I/he/she/it/we/you/they) какое слово используется.',
    correct_solution: isCorrect ? known.join(' / ') : ''
  };
}

// 01.09.2026: english (Быкова) — word_categorization, проверка МНОЖЕСТВА:
// каждое написанное ребёнком слово должно принадлежать известному набору
// слов этой категории (порядок/количество не важны — ребёнок сам решает,
// сколько слов дописать). Пустой ответ — unclear, не "ошибка" (дописывать
// все слова не обязательно).
function buildCategoryCheckTask(item: NarrowItem, writtenRaw: string | null | undefined): CheckTask {
  const known = item.knownWordSet || [];
  const knownNormalized = new Set(known.map((w) => normalizeWordAnswer(w)));
  const writtenWords = (writtenRaw || '')
    .split(',')
    .map((w) => normalizeWordAnswer(w))
    .filter((w): w is string => w !== null);

  if (writtenWords.length === 0) {
    return {
      number: item.id,
      condition: item.displayCondition,
      status: 'unclear',
      explanation: 'Не получилось разобрать написанные слова — сверьте вместе со взрослым.',
      correct_solution: ''
    };
  }

  const wrongWords = writtenWords.filter((w) => !knownNormalized.has(w));
  const isCorrect = wrongWords.length === 0;
  return {
    number: item.id,
    condition: item.displayCondition,
    status: isCorrect ? 'correct' : 'incorrect',
    explanation: isCorrect ? '' : `Не все слова подходят к этой категории — проверь ещё раз: "${wrongWords.join(', ')}".`,
    correct_solution: isCorrect ? known.join(', ') : ''
  };
}

// 01.09.2026: english (Быкова) — sentence_from_cue, лояльное сравнение
// свободного предложения (тот же принцип, что copy_and_mark_grammar):
// ошибкой считаются только ПРОПУЩЕННЫЕ/заменённые слова эталона, лишние
// слова у ребёнка не портят вердикт — та же асимметрия рисков, что и
// everywhere в проекте.
function buildSentenceCheckTask(item: NarrowItem, writtenRaw: string | null | undefined): CheckTask {
  if (!writtenRaw) {
    return {
      number: item.id,
      condition: item.displayCondition,
      status: 'unclear',
      explanation: 'Не получилось разобрать написанное предложение — сверьте вместе со взрослым.',
      correct_solution: ''
    };
  }
  // 03.09.2026: несколько допустимых вариантов ("спишите ЛЮБОЕ
  // четверостишие" — 2 печатных текста на выбор) — засчитываем совпадение
  // ХОТЯ БЫ с одним, не требуем совпадения со всеми сразу. Обычный
  // одиночный knownSentence — частный случай массива из одного элемента.
  const options = item.knownSentenceOptions && item.knownSentenceOptions.length > 0
    ? item.knownSentenceOptions
    : [item.knownSentence || ''];
  const actualRaw = tokenizeForDiff(writtenRaw);
  let bestMatch: { text: string; missing: number } | null = null;
  for (const option of options) {
    const expected = tokenizeForDiff(option);
    const actual = repairMergedWords(expected, actualRaw);
    const { missingFromExpected } = diffWords(expected, actual);
    if (!bestMatch || missingFromExpected.length < bestMatch.missing) {
      bestMatch = { text: option, missing: missingFromExpected.length };
    }
    if (missingFromExpected.length === 0) break;
  }
  const isCorrect = bestMatch !== null && bestMatch.missing === 0;
  return {
    number: item.id,
    condition: item.displayCondition,
    status: isCorrect ? 'correct' : 'incorrect',
    explanation: isCorrect ? '' : 'Предложение составлено не полностью или с ошибкой — перечитай подсказку и попробуй ещё раз.',
    correct_solution: isCorrect ? (bestMatch?.text || '') : ''
  };
}

// 02.09.2026: возвращает МАССИВ (не один CheckTask) — только
// buildIndexCheckTaskWithVerification реально может дать больше одного
// пункта (основной пример + проверочные равенства как отдельные пункты,
// см. её комментарий выше); остальные ветки оборачивают свой единственный
// результат в массив из одного элемента для единообразия сигнатуры.
export function buildIndexCheckTask(
  item: NarrowItem,
  writtenRaw: string | null | undefined,
  writtenLines: string[] | undefined,
  writtenWords?: Array<string | null>
): CheckTask[] {
  if (item.knownNumberSequence !== undefined) {
    return [buildSequenceCheckTask(item, writtenRaw)];
  }
  if (item.knownWordSequence !== undefined) {
    return [buildWordSequenceCheckTask(item, writtenWords)];
  }
  if (item.knownWordSet !== undefined) {
    return [buildCategoryCheckTask(item, writtenRaw)];
  }
  if (item.knownSentence !== undefined) {
    return [buildSentenceCheckTask(item, writtenRaw)];
  }
  if (item.knownText !== undefined) {
    // copy_and_mark_grammar обрабатывается отдельно, в verifyCopyAndMarkTask
    // (см. tryTextbookIndexCheck) — сюда попадать не должен, но безопасная
    // деградация на случай будущей ошибки вызова.
    return [
      {
        number: item.id,
        condition: item.displayCondition,
        status: 'unclear',
        explanation: 'Не получилось проверить это задание — сверьте вместе со взрослым.',
        correct_solution: ''
      }
    ];
  }

  if (item.knownWordAnswer !== undefined) {
    return [buildWordCheckTask(item, writtenRaw)];
  }

  if (item.checkEquations && item.checkEquations.length > 0) {
    return buildIndexCheckTaskWithVerification(item, writtenLines);
  }

  const written = normalizeNumericAnswer(writtenRaw);
  if (written === null) {
    return [
      {
        number: item.id,
        condition: item.displayCondition,
        status: 'unclear',
        explanation: 'Не получилось разобрать написанный ответ — сверьте вместе со взрослым.',
        correct_solution: ''
      }
    ];
  }

  const isCorrect = written === item.knownAnswer;
  return [
    {
      number: item.id,
      condition: item.displayCondition,
      status: isCorrect ? 'correct' : 'incorrect',
      // hintSteps (word_problem/word_problems) — подсказка по шагам, без чисел;
      // иначе buildDigitPlaceHint сама подставляет безопасный общий текст, если
      // hintExpression не задан или не подходит под формат "a+b"/"a-b" —
      // финальное верное число нигде не называется (см. её комментарий выше).
      explanation: isCorrect
        ? ''
        : item.hintSteps !== undefined
        ? buildStepsHint(item.hintSteps)
        : buildDigitPlaceHint(item.hintExpression, writtenRaw ?? undefined),
      correct_solution: isCorrect ? String(item.knownAnswer) : ''
    }
  ];
}

// Единая точка входа — вызывается из app/api/checks/route.ts ДО обычного
// пайплайна (checkHomeworkPhoto/checkHomeworkPhotoOpenAI), только когда
// фото одно (images.length === 1) и включён тумблер в админке. null
// означает "индекс не подошёл — используй обычный путь как раньше";
// tokensInput/tokensOutput при этом всё равно отражают реальный расход —
// детект-вызов не бесплатен, даже если матч в итоге не случился.
export async function tryTextbookIndexCheck(
  image: ImageInput,
  detailCrops: ImageInput[] = []
): Promise<{ result: CheckResult; tokensInput: number; tokensOutput: number } | null> {
  let tokensInput = 0;
  let tokensOutput = 0;

  // 22.08.2026: SUPPORTED_INDEX_SUBJECTS — предметы, для которых в
  // индексе вообще есть данные. 01.09.2026: добавлен 'english' (Быкова,
  // 8 новых answerType). 'world' по-прежнему отсекается сразу — нет ни
  // одной записи в индексе для этого предмета.
  const SUPPORTED_INDEX_SUBJECTS: Subject[] = ['math', 'russian', 'english'];

  const detect = await detectTasksOnTaskPhoto(image);
  tokensInput += detect.tokensInput;
  tokensOutput += detect.tokensOutput;

  if (!SUPPORTED_INDEX_SUBJECTS.includes(detect.subject)) {
    console.log(`[tryTextbookIndexCheck] fallback: subject "${detect.subject}" не поддерживается индексом`);
    return null;
  }

  let finalSubject: Subject = detect.subject;
  let matchResult = matchCandidatesToIndex(detect.tasks, finalSubject);

  // 21.08.2026: реальный кейс — решение в отдельной тетради без печатного
  // условия на фото (см. CLAUDE.md). Основной детект (DETECT_TASKS_PROMPT)
  // рассчитан на печатную нумерацию — на "голой" странице он нестабилен.
  // Если первая попытка не сопоставилась — пробуем ВТОРОЙ детект,
  // заточенный именно под этот случай, прежде чем сдаться и откатиться на
  // обычный пайплайн. Основной детект не трогаем (см. комментарий у
  // detectHandwrittenTasksOnSolutionPhoto выше).
  if (!matchResult.ok) {
    console.log(
      `[tryTextbookIndexCheck] основной детект не сопоставился (${matchResult.reason}) — пробуем детект для рукописной страницы`
    );
    const altDetect = await detectHandwrittenTasksOnSolutionPhoto(image);
    tokensInput += altDetect.tokensInput;
    tokensOutput += altDetect.tokensOutput;

    let altTasks = altDetect.tasks;

    // 22.08.2026: реальный прод-кейс — "Упр. 159" (номер, который ребёнок
    // написал перед решением) не распознаётся надёжно ни основным, ни
    // запасным детектом (запасной то хватает дату "13 августа" рядом,
    // то вовсе галлюцинирует текст) — оба спроектированы искать ГРАНИЦЫ
    // заданий, а не читать конкретный номер-ссылку. detectSolutionTaskNumber()
    // — уже существующая, отдельно проверенная функция именно для этого
    // (см. CLAUDE.md, «Сверка номера задания» — там её тоже уже
    // использовали для похожей цели). Применяем ТОЛЬКО когда запасной
    // детект нашёл РОВНО один блок на всю страницу (типичный случай "одно
    // упражнение — вся видимая работа") — для нескольких заданий на
    // странице один номер для всех не имеет смысла.
    let directMatch: IndexMatch | null = null;
    if (altTasks.length === 1) {
      const solutionNumber = await detectSolutionTaskNumber(image);
      tokensInput += solutionNumber.tokensInput;
      tokensOutput += solutionNumber.tokensOutput;
      if (solutionNumber.number) {
        altTasks = [{ ...altTasks[0], number: solutionNumber.number }];
        directMatch = tryDirectNumberMatch(altTasks[0], solutionNumber.number, finalSubject);
      }
    }

    // 23.08.2026: реальный прод-кейс — рукописный номер ("Упр. N") часто
    // читается неверно, независимо от того, каким из двух детектов его
    // искать. Пробуем найти задание по СОДЕРЖАНИЮ, во всём индексе, не
    // только среди записей с угаданным номером (предложение владельца) —
    // надёжнее для заданий с достаточным объёмом связного текста
    // (copy_and_mark_grammar, fill_blank_word, word_problem), где случайное
    // совпадение с чужим заданием практически исключено.
    //
    // ПРОБУЕМ ДЛЯ КАЖДОГО кандидата отдельно (не только когда он один) —
    // реальный кейс: на одной странице оказались ДВА фрагмента текста
    // (оценка за предыдущий день сверху + собственно текущее задание
    // ниже), запасной детект принял их за 2 отдельных "кандидата".
    // Кандидат, который не сопоставился ни с чем в индексе, — не
    // блокирующая ошибка, а посторонний для индекса фрагмент страницы
    // (не обязательно неверно решённое задание) — просто пропускаем его
    // молча, не проваливаем весь фотоснимок только из-за него. Если
    // сопоставился РОВНО один кандидат — используем его; если больше
    // одного (двусмысленность, какое из НАШИХ заданий это) — безопасно
    // откатываемся на обычный matchCandidatesToIndex ниже.
    if (!directMatch) {
      const contentMatches = altTasks
        .map((candidate) => {
          const entry = findEntryByTextContent(candidate.condition, finalSubject);
          if (!entry) return null;
          const items = buildNarrowItems(entry);
          if (items.length === 0) return null;
          return { candidate, entry, items } as IndexMatch;
        })
        .filter((m): m is IndexMatch => m !== null);

      if (contentMatches.length === 1) {
        directMatch = contentMatches[0];
      }
    }

    // Предмет берём от ОСНОВНОГО детекта (finalSubject уже установлен
    // выше и прошёл проверку SUPPORTED_INDEX_SUBJECTS) — запасной детект
    // на "голых" страницах иногда ошибается в предмете (реальный случай:
    // вернул "math" на явно русскоязычном тексте), поэтому используем его
    // только для границ/номера задания, не для переопределения предмета.
    matchResult = directMatch ? { ok: true, matches: [directMatch] } : matchCandidatesToIndex(altTasks, finalSubject);
  }

  if (!matchResult.ok) {
    console.log(`[tryTextbookIndexCheck] fallback: ${matchResult.reason}`);
    return null;
  }

  // 22.08.2026: copy_and_mark_grammar (русский язык) обрабатывается ОТДЕЛЬНО
  // от остального пакетного вызова — см. verifyCopyAndMarkTask и комментарий
  // у buildIndexNarrowVerificationPrompt (почему именно так, реальный
  // прод-кейс с галлюцинацией цитаты расхождения). Координаты для физической
  // изоляции берём с candidate (детект уже нашёл границы задания на фото).
  const copyMatches = matchResult.matches.filter((m) => m.items.some((it) => it.knownText !== undefined));
  const otherItems = matchResult.matches
    .filter((m) => !m.items.some((it) => it.knownText !== undefined))
    .flatMap((m) => m.items);

  const tasks: CheckTask[] = [];

  if (otherItems.length > 0) {
    const verification = await callOpenAIResponsesJsonWithRetry(
      {
        model: MODEL,
        reasoning: { effort: 'none' },
        input: [
          {
            role: 'user',
            content: [
              { type: 'input_text', text: buildIndexNarrowVerificationPrompt(otherItems) },
              toImageBlock(image),
              ...detailCrops.map(toImageBlock)
            ]
          }
        ]
      },
      (text) =>
        extractJson(text) as {
          results?: Array<{
            id: string;
            written_answer?: string | null;
            lines?: string[];
            // 01.09.2026: english (Быкова) — verb_form_fill, слова по
            // позициям пропусков в одном предложении.
            written_words?: Array<string | null>;
          }>;
        }
    );
    tokensInput += verification.tokensInput;
    tokensOutput += verification.tokensOutput;

    const writtenById = new Map<string, string | null>();
    const linesById = new Map<string, string[] | undefined>();
    const wordsById = new Map<string, Array<string | null> | undefined>();
    for (const r of verification.parsed?.results || []) {
      if (r && typeof r.id === 'string') {
        writtenById.set(r.id, r.written_answer ?? null);
        linesById.set(r.id, r.lines);
        wordsById.set(r.id, r.written_words);
      }
    }
    // 24.08.2026: реальный прод-кейс — точечный recheck слов-ответов
    // (fill_blank_word) ПРОБОВАЛИ добавить (23.08.2026, по образцу уже
    // работающего recheck для copy_and_mark_grammar), но диагностика сырых
    // ответов модели на реальном фото показала обратный эффект: recheck
    // формулировался как "не удалось надёжно определить ответ — перечитай"
    // — и модель, зная, что её первый ответ "не подошёл", иногда не
    // перечитывала нейтрально, а СОЧИНЯЛА другое слово, ближе к тому,
    // что "ожидается". В одном из 3 прогонов это стёрло РЕАЛЬНУЮ ошибку
    // ребёнка (слово "золотой", стабильно прочитанное 3 из 3 раз БЕЗ
    // recheck) — recheck превратил её в ложное "correct". Без recheck те
    // же 3 прогона стабильно давали 5 из 6 верно распознанных слов;
    // с recheck результат стал НЕПРЕДСКАЗУЕМЫМ, в том числе иногда хуже.
    // Убрано полностью — единственная попытка снова, как и для остальных
    // числовых типов (см. buildWordCheckTask). recheckWordAnswers удалена
    // из файла вместе с этим изменением — не оставляем неиспользуемый код,
    // который подтверждённо ухудшал результат.
    //
    // Доп. диагностика тем же вечером (8 прогонов, только первая попытка):
    // одно слово ("глазок") читается стабильно одинаково во всех прогонах
    // (реальная ошибка ребёнка, не шум) — а другое ("корзинка") даёт
    // РАЗНОЕ прилагательное почти в каждом прогоне ("большая", "красивая",
    // "облазая", "красная", "жёлтая" — ни разу не совпадающее ожидаемому
    // "белая"). Непохоже на обычный шум распознавания — вероятно, именно
    // в этом месте фото что-то физически мешает читать (та самая исходная
    // пометка про "наложения и исправления"). Recheck такую нестабильность
    // не лечит (см. выше) — если возвращаться к этой проблеме, разумнее
    // начинать с самого фото (проверить на фото без правок/зачёркиваний),
    // а не с промпта.
    tasks.push(
      ...otherItems.flatMap((item) =>
        buildIndexCheckTask(item, writtenById.get(item.id), linesById.get(item.id), wordsById.get(item.id))
      )
    );
  }

  for (const match of copyMatches) {
    for (const item of match.items) {
      if (item.knownText === undefined) continue;
      const result = await verifyCopyAndMarkTask(image, item, match.candidate.yStartPercent, match.candidate.yEndPercent);
      tokensInput += result.tokensInput;
      tokensOutput += result.tokensOutput;
      tasks.push(result.task);
    }
  }

  // 02.09.2026: реальный прод-кейс — buildIndexCheckTaskWithVerification
  // теперь может вернуть НЕСКОЛЬКО пунктов на один item (основной пример +
  // проверочные равенства, см. её комментарий выше), и их служебные id
  // вида "5a-check-18" (нужны только для уникальности при формировании
  // массива, не для показа) утекли прямо в интерфейс — components/
  // CheckResultView.tsx выводит "Задание {number}" как есть, без
  // фильтрации. Тот же паттерн финальной перенумерации подряд (1, 2, 3...),
  // что уже применяется в конце checkHomeworkPhotoOpenAI (там по той же
  // причине — номера от модели/кода не предназначены для показа), просто
  // раньше в этом пайплайне такого шага не требовалось, пока каждый item
  // не мог дать больше одного пункта.
  tasks.forEach((t, i) => {
    t.number = String(i + 1);
  });

  const { grade, general_comment } = computeGradeAndComment(tasks);

  console.log(
    `[tryTextbookIndexCheck] успех: ${tasks.length} пункт(ов) из ${matchResult.matches.length} задания(й), токены вх=${tokensInput}, вых=${tokensOutput}`
  );

  return {
    result: { subject: finalSubject, tasks, grade, general_comment },
    tokensInput,
    tokensOutput
  };
}

// 08.09.2026: см. подробный комментарий у места вызова ниже (перед
// tasks.sort в checkHomeworkPhotoOpenAI). Парсит уже готовый reasoning
// модели ("Утверждение: «...» — истинно/ложно. Ученик отметил: да/нет.")
// и разбивает один сгруппированный task ("Отметь верные утверждения",
// condition через ";") на несколько отдельных — только когда в reasoning
// нашлось 2+ таких пунктов (иначе это не тот формат, task не трогаем).
const GROUPED_STATEMENT_CLAUSE =
  /Утверждение:\s*[«"]([^»"]+)[»"]\s*[—-]\s*(истинно|ложно)\.\s*Ученик отметил:\s*(да|нет)/gi;

// 09.09.2026: ЕЩЁ один реальный прод-кейс — четвёртый формат reasoning:
// "Утверждения: «текст» — ложно, не отмечено; «текст2» — истинно,
// отмечено; ..." — метка "Утверждения:" (множественное число, ОДИН раз в
// начале) вместо "Утверждение:" перед каждым пунктом, запятая+"отмечено"
// вместо "Ученик отметил: да/нет". GROUPED_STATEMENT_CLAUSE не матчится
// (нет "Утверждение:" перед каждой цитатой) — этот паттерн не требует
// такой метки вообще, ищет саму пару "«текст» — вердикт, отметка" где
// угодно в тексте.
const QUOTED_VERDICT_MARK_CLAUSE =
  /[«"]([^»"]+)[»"]\s*[—-]\s*(истинно|ложно)\s*,\s*(не\s*отмечен\w*|отмечен\w*)/gi;

// 09.09.2026: реальный прод-кейс — модель не всегда цитирует текст
// утверждения в reasoning. Встретились ещё два формата: "Утверждение 1:
// ложно..." (с номером) и просто "Утверждение: ложно..." 5 раз подряд без
// какого-либо текста утверждения вообще (GROUPED_STATEMENT_CLAUSE не
// матчится ни на один из них — нет обязательных кавычек). Этот паттерн —
// запасной, ловит оба случая разом (номер после "Утверждение" — опционален),
// но без текста самого утверждения — сопоставление с частями condition
// делается ПОЗИЦИОННО (см. использование ниже), только когда количество
// найденных пунктов совпадает РОВНО с числом частей condition через ";" —
// иначе гадать, какой вердикт к какому пункту относится, слишком рискованно.
const BARE_STATEMENT_CLAUSE = /Утверждение\s*\d*:\s*(истинно|ложно)\.\s*Ученик отметил:\s*(да|нет)\.?/gi;

// Тот же фильтр, что и в checkHomeworkPhotoOpenAI ниже (историю про баг с
// \w на кириллице см. в комментарии там) — используется и здесь, чтобы
// splitGroupedStatementTasks() могла заранее проверить, не спрячет ли
// разбиение группы вообще ВСЕ получившиеся под-задания разом.
const UNMARKED_FALSE_STATEMENT =
  /(?<![а-яёa-z])ложн[оаяе][\s\S]{0,120}?(не\s*отмет[а-яё]*|отмет[а-яё]*\s*:?\s*нет)/i;

function wouldBeHiddenAsUnmarkedFalse(t: CheckTask): boolean {
  return (
    t.status === 'correct' &&
    !t.condition.includes(';') &&
    t.condition.length <= 80 &&
    UNMARKED_FALSE_STATEMENT.test(t.reasoning || '')
  );
}

function buildStatementSubTask(
  task: CheckTask,
  subIndex: number,
  condition: string,
  isFalse: boolean,
  isMarked: boolean
): CheckTask {
  // ложно + не отмечено, ИЛИ истинно + отмечено → ученик прав.
  const isChildCorrect = isFalse === !isMarked;
  // 09.09.2026: буквенный суффикс к родительскому номеру ("2a", "2b"...) —
  // тот же формат, что уже используется в проекте (см. пример "10a" в
  // самом системном промпте). Раньше все под-задания получали ОДИНАКОВЫЙ
  // номер родителя, и это скрадывалось финальной сквозной перенумерацией
  // всего списка (1,2,3...) — но её убрали по прямой просьбе владельца
  // (номера в приложении должны совпадать с реальными номерами из
  // учебника, а не быть выдуманной сквозной нумерацией), так что теперь
  // без суффикса несколько карточек показывались бы под одним и тем же
  // номером.
  const number = `${task.number}${String.fromCharCode(97 + subIndex)}`;
  return {
    number,
    condition,
    yStartPercent: task.yStartPercent,
    yEndPercent: task.yEndPercent,
    reasoning: `Утверждение: ${isFalse ? 'ложно' : 'истинно'}. Ученик отметил: ${
      isMarked ? 'да' : 'нет'
    }.`,
    status: isChildCorrect ? 'correct' : 'incorrect',
    explanation: '',
    correct_solution: ''
  };
}

// 09.09.2026: реальный прод-кейс навёл на риск — на странице про
// прямоугольник среди 5 утверждений всегда есть истинные (их reasoning
// никогда не содержит "ложно", фильтр их не тронет), поэтому там
// разбиение безопасно. Но если КОГДА-НИБУДЬ на другой странице/предмете
// все утверждения в группе окажутся ложными, а ученик верно ничего не
// отметит — фильтр ниже скрыл бы ВСЕ получившиеся под-задания разом, и
// целое задание пропало бы из результата без следа (тот же класс риска,
// что уже ловили на многошаговой задаче с краткой записью — см. историю
// "единственная точка отказа" выше). Если разбиение скрыло бы КАЖДОЕ
// под-задание — не разбиваем вовсе, возвращаем null (вызывающий код
// оставляет один сгруппированный task как есть, видимый целиком) —
// лучше простыня текста, чем полное исчезновение.
function applySafetyNet(task: CheckTask, subTasks: CheckTask[]): CheckTask[] | null {
  if (!subTasks.every(wouldBeHiddenAsUnmarkedFalse)) return subTasks;
  // Постоянный (не за debug-флагом) лог — этот случай подтверждённо
  // происходил в проде (задание пропадало из ответа целиком) до того,
  // как появилась эта подстраховка. Если сработает снова — сразу видно
  // в Vercel Runtime Logs, без нужды ловить сырой JSON через devtools.
  console.log(
    `[splitGroupedStatementTasks] подстраховка сработала: все ${subTasks.length} под-задания были бы скрыты, оставлен один сгруппированный task ("${task.condition.slice(0, 60)}...")`
  );
  return null;
}

type ParsedClause = { text: string; isFalse: boolean; isMarked: boolean };

// Пробует форматы reasoning, где текст утверждения процитирован в
// кавычках (самый надёжный случай — сопоставление с condition идёт по
// тексту, а не по порядку). Несколько под-форматов встретились в проде
// в один день — пробуем по очереди, используем первый, что дал 2+
// результата.
function parseQuotedClauses(reasoning: string): ParsedClause[] {
  const viaLabeled = [...reasoning.matchAll(GROUPED_STATEMENT_CLAUSE)].map((m) => ({
    text: m[1].trim(),
    isFalse: m[2].toLowerCase() === 'ложно',
    isMarked: m[3].toLowerCase() === 'да'
  }));
  if (viaLabeled.length >= 2) return viaLabeled;

  return [...reasoning.matchAll(QUOTED_VERDICT_MARK_CLAUSE)].map((m) => ({
    text: m[1].trim(),
    isFalse: m[2].toLowerCase() === 'ложно',
    isMarked: !m[3].toLowerCase().trim().startsWith('не')
  }));
}

function splitGroupedStatementTasks(tasks: CheckTask[]): CheckTask[] {
  const result: CheckTask[] = [];
  for (const task of tasks) {
    if (!task.condition.includes(';') || !task.reasoning) {
      result.push(task);
      continue;
    }

    // Попытка 1: reasoning цитирует текст каждого утверждения в кавычках
    // — самый надёжный случай, текст сопоставляется однозначно, не
    // завися от порядка (см. parseQuotedClauses про конкретные форматы).
    const quoted = parseQuotedClauses(task.reasoning);
    if (quoted.length >= 2) {
      const firstClauseIndex = task.condition.indexOf(quoted[0].text);
      const stem = firstClauseIndex > 0 ? task.condition.slice(0, firstClauseIndex) : '';
      const subTasks = quoted.map((c, i) =>
        buildStatementSubTask(task, i, stem ? `${stem}${c.text}` : c.text, c.isFalse, c.isMarked)
      );
      const safe = applySafetyNet(task, subTasks);
      result.push(...(safe ?? [task]));
      continue;
    }

    // Попытка 2: reasoning БЕЗ текста утверждения ("Утверждение: ложно."
    // или "Утверждение 3: ложно." — см. BARE_STATEMENT_CLAUSE). Сопоставляем
    // ПОЗИЦИОННО с частями condition через ";", только если количество
    // совпало РОВНО — иначе рискованно гадать, какой вердикт к какому
    // пункту относится, оставляем task как есть.
    const bare = [...task.reasoning.matchAll(BARE_STATEMENT_CLAUSE)];
    const segments = task.condition
      .split(';')
      .map((s) => s.trim())
      .filter(Boolean);
    if (bare.length >= 2 && bare.length === segments.length) {
      const lastColonIdx = segments[0].lastIndexOf(':');
      const stem = lastColonIdx >= 0 ? segments[0].slice(0, lastColonIdx + 1) + ' ' : '';
      const subTasks = bare.map((m, i) =>
        buildStatementSubTask(
          task,
          i,
          i === 0 ? segments[0] : `${stem}${segments[i]}`,
          m[1].toLowerCase() === 'ложно',
          m[2].toLowerCase() === 'да'
        )
      );
      const safe = applySafetyNet(task, subTasks);
      result.push(...(safe ?? [task]));
      continue;
    }

    result.push(task);
  }
  return result;
}

// 09.09.2026: реальный прод-кейс от владельца — у заданий "перевод единиц
// измерения" ("5 дм 4 см = ? см", "49 дм = ? м ? дм" и т.п.) поле
// "correct_solution" ПОСТОЯННО пустое, даже когда status==="correct" — в
// отличие от голой арифметики/цепочек чисел (там код-верификация уже
// давно считает и заполняет это поле), для перевода единиц такой защиты
// не было вовсе, и модель просто никогда не заполняла текст ответа для
// этого конкретного типа заданий (воспроизводилось во ВСЕХ присланных
// владельцем JSON за сегодня, не разовый сбой). В интерфейсе это
// выглядело как "✓" без единого пояснения — тот же класс проблемы, что
// уже решали для арифметики, просто для другого типа условия.
// Перевод единиц измерения — чисто механическая арифметика (1 м = 10 дм
// = 100 см = 1000 мм), её можно полностью посчитать по ТЕКСТУ условия, не
// обращаясь к модели и не трогая фото вообще — в отличие от арифметики/
// цепочек чисел, здесь даже не нужен OCR-вызов: что писал ребёнок знать не
// нужно, если статус уже "correct" (значит он написал верно) — достаточно
// просто посчитать, каким должен быть правильный ответ, и это же значение
// совпадает с тем, что написал ребёнок, раз task уже помечен верным.
const UNIT_TO_MM: Record<string, number> = { м: 1000, дм: 100, см: 10, мм: 1 };

// 09.09.2026: тот же баг, что уже чинили раньше в этом файле (см.
// UNMARKED_FALSE_STATEMENT выше) — `\b` в JavaScript определяется через
// `\w`, а `\w` не матчит кириллицу, поэтому `\b` сразу после "дм"/"см" не
// срабатывал вообще (ни разу не находил переход "буква → не-буква" на
// кириллице). Заменено на негативный lookahead "не кириллическая буква
// сразу после" — заодно корректно разруливает "мм" vs "м" через
// бэктрекинг (если короткая альтернатива "м" не проходит lookahead из-за
// второй "м" следом, движок сам пробует более длинную "мм").
const UNIT_BOUNDARY = '(?![а-яёА-ЯЁ])';

function parseUnitQuantityMm(text: string): number | null {
  const re = new RegExp(`(\\d+)\\s*(м|дм|см|мм)${UNIT_BOUNDARY}`, 'g');
  let total = 0;
  let found = false;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text))) {
    total += parseInt(m[1], 10) * UNIT_TO_MM[m[2]];
    found = true;
  }
  return found ? total : null;
}

function isUnitConversionTask(condition: string): boolean {
  return (
    /=\s*\?/.test(condition) && new RegExp(`\\d\\s*(м|дм|см|мм)${UNIT_BOUNDARY}`).test(condition)
  );
}

// Возвращает текст правильного ответа ("54" для одной целевой единицы,
// "4 м 9 дм" для нескольких) или null, если условие не удалось разобрать
// (не наш формат, или количество не делится ровно на целевую единицу —
// в этом случае просто не трогаем task, а не гадаем).
function computeUnitConversion(condition: string): string | null {
  const eqIdx = condition.indexOf('=');
  if (eqIdx === -1) return null;
  const lhs = condition.slice(0, eqIdx);
  const rhs = condition.slice(eqIdx + 1);

  const totalMm = parseUnitQuantityMm(lhs);
  if (totalMm == null) return null;

  const targetUnitsRe = new RegExp(`\\?\\s*(м|дм|см|мм)${UNIT_BOUNDARY}`, 'g');
  const targetUnits = [...rhs.matchAll(targetUnitsRe)].map((m) => m[1]);
  if (targetUnits.length === 0) return null;

  if (targetUnits.length === 1) {
    const unitMm = UNIT_TO_MM[targetUnits[0]];
    if (totalMm % unitMm !== 0) return null;
    return String(totalMm / unitMm);
  }

  let remaining = totalMm;
  const parts: string[] = [];
  targetUnits.forEach((unit, i) => {
    const unitMm = UNIT_TO_MM[unit];
    const isLast = i === targetUnits.length - 1;
    const value = isLast ? Math.round(remaining / unitMm) : Math.floor(remaining / unitMm);
    remaining -= value * unitMm;
    parts.push(`${value} ${unit}`);
  });
  return parts.join(' ');
}

// 09.09.2026: тот же пробел, что и у перевода единиц измерения выше, но
// для "цепочки чисел" ("Запиши пропущенные числа и знаки действий: 5 →
// 25 → 7 → 33 → 20 → 16.") — уже существующая код-верификация
// (isSimpleNumberChain, шаг 3.6) срабатывает только когда ОСНОВНОЙ вызов
// САМ разбил серию на отдельные task вида "5 → 25" (см. "Известное
// неполное покрытие" выше) — когда он вместо этого вернул ОДИН
// сгруппированный task с полным текстом, ни код-верификация, ни
// заполнение correct_solution не срабатывают вовсе, хотя контрольные
// числа (кружки на диаграмме) уже целиком присутствуют в самом condition
// — считать их можно, не трогая фото и не спрашивая модель. Тот же
// принцип: трогаем только уже решённый моделью как "correct" task,
// достраиваем ТЕКСТ ответа (разницы между соседними числами), не меняем
// вердикт.
function extractChainNumbers(condition: string): number[] | null {
  // Минимум 3 числа подряд через "→" (1 переход — это уже отдельный
  // task вида "5 → 25" из isSimpleNumberChain, сюда попадать не должен).
  const chainMatch = condition.match(/\d+(?:\s*→\s*\d+){2,}/);
  if (!chainMatch) return null;
  return chainMatch[0].split('→').map((s) => parseInt(s.trim(), 10));
}

function isGroupedNumberChainTask(condition: string): boolean {
  return extractChainNumbers(condition) !== null;
}

function computeNumberChainSolution(condition: string): string | null {
  const numbers = extractChainNumbers(condition);
  if (!numbers || numbers.length < 2) return null;
  const parts: string[] = [];
  for (let i = 1; i < numbers.length; i++) {
    const diff = numbers[i] - numbers[i - 1];
    parts.push(diff >= 0 ? `+${diff}` : String(diff));
  }
  return parts.join(', ');
}

