// ПОЛНОСТЬЮ в коде (не запрашивается у модели) — оба операнда уже есть
// в "expression" из OCR-распознавания на этом же шаге, раскладка на
// разряды детерминирована, риска "модель посчитала неверно" тут нет.
const PLACE_NAMES = ['единиц', 'десятков', 'сотен', 'тысяч'];

function buildDigitPlaceHint(expression: string | undefined, writtenAnswer: string | null | undefined): string {
  const fallback = 'Ответ записан неверно — пересчитай пример ещё раз.';
  const match = (expression || '').match(/^\s*(\d+)\s*([+\-])\s*(\d+)/);
  if (!match) return fallback;

  const [, aStr, opSymbol, bStr] = match;
  const opName = opSymbol === '+' ? 'сложение' : 'вычитание';
  const maxLen = Math.max(aStr.length, bStr.length);
  const aDigits = aStr.padStart(maxLen, '0').split('');
  const bDigits = bStr.padStart(maxLen, '0').split('');

  const parts: string[] = [];
  for (let i = maxLen - 1; i >= 0; i--) {
    const place = PLACE_NAMES[maxLen - 1 - i] || `разряда ${maxLen - i}`;
    parts.push(`${opName} ${place}: ${aDigits[i]}${opSymbol}${bDigits[i]}=?`);
  }

  const writtenPart = writtenAnswer ? `Ты написал ${writtenAnswer}. ` : '';
  return `${writtenPart}Проверь ${parts.join(' и ')}.`;
}

// 18.08.2026: тот же принцип, что и у голой арифметики выше, применён к
// "цепочкам чисел" (условие вида "5 → 25" — ученик должен вписать знак
// действия и число, переводящее левое число в правое). Реальный
// прод-баг: модель ложно пометила ошибкой корректно заполненное
// окошко — то же "читаю и вычисляю одновременно, без проверки". Оба
// числа цепочки уже даны в самом условии (напечатаны в тетради), значит
// верное значение перехода — просто end - start, считается в коде, без
// доверия модели. Модель отвечает ТОЛЬКО за то, что физически написано
// в окошке — не вычисляет и не оценивает.
function isSimpleNumberChain(condition: string): boolean {
  const text = (condition || '').trim();
  return /^\d+\s*(?:→|->)\s*\d+$/.test(text);
}

function parseNumberChain(condition: string): { start: number; end: number } | null {
  const match = condition.trim().match(/^(\d+)\s*(?:→|->)\s*(\d+)$/);
  if (!match) return null;
  return { start: parseInt(match[1], 10), end: parseInt(match[2], 10) };
}

