// задания в каждом элементе ответа, чтобы сопоставить результат обратно.
function isSimpleArithmeticExpression(condition: string): boolean {
  const text = (condition || '').trim();
  // 02.09.2026: реальный прод-кейс — школьная тетрадь по делению записывает
  // деление через ":" ("16 : 1 = ?"), а не "/" или "÷". Без ":" в этом
  // классе ни один пример деления не попадал под isSimpleArithmeticExpression
  // вообще — вся страница с примерами на деление проверялась моделью "на
  // глаз", без код-верификации, и реальную ошибку OCR (16 прочитано как 26)
  // некому было поймать.
  return /^\d+\s*[+\-×÷:*/]\s*\d+\s*=\s*\??\s*$/.test(text);
}

